"""Audit of the HPO term expansion behind evidence class E1 (design sections 3.1 and 4.2; assumption A7).

Each target symptom is expanded to the descendants of its crosswalk HPO terms. This script
measures what that expansion pulls in, per symptom and per descendant term, over the genes of
the reconstruction: how many Human-GEM genes each term contributes, how many are reachable only
through that term, the provenance of the annotations (OMIM versus Orphanet disease entries) and
the distribution of HPO frequency qualifiers. Terms that name a diagnosis (for example Attention
deficit hyperactivity disorder) or a construct other than the target symptom (Restless legs under
Restlessness) are the diagnosis-proxy leak that assumption A7 warns about, and they are listed so
the crosswalk can exclude them explicitly (column excluded_hpo_ids).

Writes docs/hpo_term_audit.md and data/processed/hpo_term_audit.json.

Usage:
  python experiments/audit_hpo_term_expansion.py
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from mechanistic_pathway_learning.evidence.load_monogenic_phenotype_annotations import (
    descendants_of,
    load_hpo_is_a_parents_from_obo,
    load_hpo_term_names_from_obo,
    parse_frequency_qualifier,
    parse_genes_to_phenotype,
    read_crosswalk_hpo_terms,
)

FREQUENCY_QUALIFIER_LABELS = {
    "HP:0040280": "Obligate (100%)",
    "HP:0040281": "Very frequent (80-99%)",
    "HP:0040282": "Frequent (30-79%)",
    "HP:0040283": "Occasional (5-29%)",
    "HP:0040284": "Very rare (1-4%)",
    "HP:0040285": "Excluded (0%)",
}


def read_human_gem_gene_symbols(genes_table_path: Path) -> set[str]:
    gene_symbols: set[str] = set()
    with open(genes_table_path, encoding="utf-8") as genes_file:
        for row in csv.DictReader(genes_file, delimiter="\t", quotechar='"'):
            for symbol in (row.get("geneSymbols") or "").split(";"):
                if symbol.strip():
                    gene_symbols.add(symbol.strip())
    return gene_symbols


def frequency_bucket(raw_frequency: str) -> str:
    raw_frequency = (raw_frequency or "").strip()
    if raw_frequency in FREQUENCY_QUALIFIER_LABELS:
        return FREQUENCY_QUALIFIER_LABELS[raw_frequency]
    if "/" in raw_frequency:
        return "fraction n/m"
    if raw_frequency.endswith("%"):
        return "percentage"
    return "not reported"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--crosswalk", type=Path, default=Path("docs/symptom_crosswalk.csv"))
    parser.add_argument("--hpo-obo", type=Path, default=Path("data/raw/hpo/hp.obo"))
    parser.add_argument("--hpo-annotations", type=Path, default=Path("data/raw/hpo/genes_to_phenotype.txt"))
    parser.add_argument("--human-gem-genes", type=Path, default=Path("data/raw/Human-GEM/model/genes.tsv"))
    parser.add_argument("--markdown-output", type=Path, default=Path("docs/hpo_term_audit.md"))
    parser.add_argument("--json-output", type=Path, default=Path("data/processed/hpo_term_audit.json"))
    arguments = parser.parse_args()

    parents_by_term = load_hpo_is_a_parents_from_obo(arguments.hpo_obo)
    term_names = load_hpo_term_names_from_obo(arguments.hpo_obo)
    crosswalk = read_crosswalk_hpo_terms(arguments.crosswalk)
    annotation_rows = parse_genes_to_phenotype(arguments.hpo_annotations)
    gem_symbols = read_human_gem_gene_symbols(arguments.human_gem_genes)
    gem_rows = [row for row in annotation_rows if row.get("gene_symbol") in gem_symbols]

    audit: dict[str, dict] = {}
    lines = [
        "# HPO term expansion audit (generated by experiments/audit_hpo_term_expansion.py)",
        "",
        "Each target symptom is expanded to the is_a descendants of its crosswalk HPO terms. The tables show what that expansion pulls in over Human-GEM genes: genes contributed by each descendant term, genes reachable only through that term, provenance of the annotation rows (OMIM versus Orphanet disease entries) and the HPO frequency qualifiers. Terms listed in the crosswalk column excluded_hpo_ids are removed from the expansion (with their own descendants) and are shown here with their counts so the exclusion is auditable.",
        "",
        f"Source rows: {len(annotation_rows)} gene-phenotype annotations, {len(gem_rows)} on Human-GEM genes ({len(gem_symbols)} symbols in genes.tsv).",
        "",
    ]
    for symptom, (root_ids, excluded_ids) in crosswalk.items():
        term_to_root: dict[str, str] = {}
        for root_id in root_ids:
            for descendant_id in descendants_of(root_id, parents_by_term):
                term_to_root[descendant_id] = root_id
        excluded_terms: set[str] = set()
        for excluded_id in excluded_ids:
            excluded_terms |= descendants_of(excluded_id, parents_by_term)
        genes_by_term: dict[str, set[str]] = defaultdict(set)
        provenance_by_term: dict[str, Counter] = defaultdict(Counter)
        frequency_by_term: dict[str, Counter] = defaultdict(Counter)
        for row in gem_rows:
            term_id = row.get("hpo_id", "")
            if term_id not in term_to_root:
                continue
            genes_by_term[term_id].add(row["gene_symbol"])
            provenance_by_term[term_id][(row.get("disease_id") or "").split(":")[0] or "unknown"] += 1
            frequency_by_term[term_id][frequency_bucket(row.get("frequency", ""))] += 1
        kept_terms = {term for term in genes_by_term if term not in excluded_terms}
        genes_kept = set().union(*[genes_by_term[term] for term in kept_terms]) if kept_terms else set()
        genes_all = set().union(*genes_by_term.values()) if genes_by_term else set()
        frequency_values = [parse_frequency_qualifier(row.get("frequency", "")) for row in gem_rows if row.get("hpo_id", "") in kept_terms]
        known_frequencies = [value for value in frequency_values if value is not None]
        audit[symptom] = {
            "root_terms": root_ids,
            "excluded_terms": sorted(excluded_ids),
            "descendant_terms_total": len(term_to_root),
            "descendant_terms_with_gem_annotations": len(genes_by_term),
            "human_gem_genes_before_exclusion": len(genes_all),
            "human_gem_genes_after_exclusion": len(genes_kept),
            "annotation_rows_kept": len(frequency_values),
            "annotation_rows_with_known_frequency": len(known_frequencies),
            "mean_known_frequency": (sum(known_frequencies) / len(known_frequencies)) if known_frequencies else None,
            "terms": [],
        }
        root_description = ", ".join(f"{root} {term_names.get(root, '?')}" for root in root_ids) or "none"
        excluded_description = ", ".join(f"{term} {term_names.get(term, '?')}" for term in excluded_ids) or "none"
        frequency_description = (
            f"Annotation rows kept: {len(frequency_values)}, of which {len(known_frequencies)} carry a frequency (mean {audit[symptom]['mean_known_frequency']:.2f})."
            if known_frequencies else f"Annotation rows kept: {len(frequency_values)}; none carries a frequency."
        )
        lines += [
            f"## {symptom}",
            "",
            f"Roots: {root_description}. Excluded: {excluded_description}. Descendant terms: {len(term_to_root)}; with Human-GEM annotations: {len(genes_by_term)}. "
            f"Human-GEM genes: {len(genes_all)} before exclusion, {len(genes_kept)} after. {frequency_description}",
            "",
            "| term | name | status | genes | genes only via this term | OMIM rows | ORPHA rows | frequency qualifiers (rows) |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for term_id, genes in sorted(genes_by_term.items(), key=lambda item: -len(item[1])):
            other_genes = set().union(*[other for other_term, other in genes_by_term.items() if other_term != term_id]) if len(genes_by_term) > 1 else set()
            only_here = len(genes - other_genes)
            status = "excluded" if term_id in excluded_terms else ("root" if term_id in root_ids else "descendant")
            frequency_summary = "; ".join(f"{label} {count}" for label, count in frequency_by_term[term_id].most_common())
            audit[symptom]["terms"].append({"term": term_id, "name": term_names.get(term_id, "?"), "status": status, "genes": len(genes), "genes_only_via_term": only_here,
                                            "omim_rows": provenance_by_term[term_id].get("OMIM", 0), "orpha_rows": provenance_by_term[term_id].get("ORPHA", 0),
                                            "frequency_rows": dict(frequency_by_term[term_id])})
            lines.append(f"| {term_id} | {term_names.get(term_id, '?')} | {status} | {len(genes)} | {only_here} | {provenance_by_term[term_id].get('OMIM', 0)} | {provenance_by_term[term_id].get('ORPHA', 0)} | {frequency_summary} |")
        lines.append("")
    arguments.json_output.parent.mkdir(parents=True, exist_ok=True)
    arguments.json_output.write_text(json.dumps(audit, indent=1))
    arguments.markdown_output.write_text("\n".join(lines) + "\n")
    for symptom, entry in audit.items():
        print(f"{symptom:30s} genes before {entry['human_gem_genes_before_exclusion']:4d} after {entry['human_gem_genes_after_exclusion']:4d}  terms {entry['descendant_terms_with_gem_annotations']:3d}  rows {entry['annotation_rows_kept']:5d} with frequency {entry['annotation_rows_with_known_frequency']:5d}")


if __name__ == "__main__":
    main()

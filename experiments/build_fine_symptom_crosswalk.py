"""Build the fine symptom crosswalk from the coarse one (decision 9.58).

Reads docs/symptom_crosswalk.csv, configs/symptom_construct_additions.csv, configs/fine_construct_term_overrides.csv,
hp.obo and the SIDER MedDRA vocabulary; writes docs/symptom_crosswalk_fine.csv, configs/impc_symptom_crosswalk_fine.csv
and docs/fine_symptom_constructs.md (generated, stamped). The rules are in evidence/symptom_constructs.py: a coarse
row's terms are shared out among its HPO roots by the ontology's own vocabulary, an added construct takes the MedDRA
preferred terms whose words the ontology uses for it, and every assignment is listed with how it was made.

Usage:
  python experiments/build_fine_symptom_crosswalk.py
  python experiments/build_fine_symptom_crosswalk.py --check   # exit 1 when the committed files differ from a fresh build
"""
from __future__ import annotations

import argparse
import csv
import gzip
import sys
from pathlib import Path

from mechanistic_pathway_learning.documentation import provenance_stamp
from mechanistic_pathway_learning.evidence.symptom_constructs import (
    ADDITIONS_PATH,
    COARSE_CROSSWALK_PATH,
    CROSSWALK_COLUMNS,
    FINE_COLUMNS,
    FINE_CROSSWALK_PATH,
    IMPC_COARSE_PATH,
    IMPC_COLUMNS,
    IMPC_FINE_PATH,
    TERM_OVERRIDES_PATH,
    HpoVocabulary,
    build_fine_crosswalk,
    fine_impc_rows,
    phrase,
    read_rows,
    read_term_overrides,
    split_cell,
    write_rows,
)

DEFAULT_OBO = Path("data/raw/hpo/hp.obo")
DEFAULT_SIDER_SIDE_EFFECTS = Path("data/raw/sider_4.1/meddra_all_se.tsv.gz")
DEFAULT_PAGE = Path("docs/fine_symptom_constructs.md")


def meddra_preferred_terms(path: Path) -> list[str]:
    """Every distinct MedDRA preferred term name SIDER uses (column 6 of rows whose column 4 is PT)."""
    terms = set()
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for row in csv.reader(handle, delimiter="\t"):
            if len(row) >= 6 and row[3] == "PT":
                terms.add(row[5])
    return sorted(terms)


def complete_addition(addition: dict[str, str], vocabulary: HpoVocabulary, preferred_terms: list[str]) -> dict[str, str]:
    """An added construct named by id only: its name from the ontology, its MedDRA terms the preferred terms whose
    words the ontology uses for the root or a kept descendant."""
    root_id = split_cell(addition.get("hpo_ids"))[0]
    phrases = vocabulary.phrases_of(root_id, split_cell(addition.get("excluded_hpo_ids")))
    matched = [term for term in preferred_terms if phrase(term) in phrases]
    completed = {column: addition.get(column, "") for column in CROSSWALK_COLUMNS}
    completed["hpo_names"] = vocabulary.names_by_term[root_id]
    completed["meddra_preferred_terms"] = ";".join(matched)
    completed.setdefault("identifier_status", "")
    completed["identifier_status"] = completed["identifier_status"] or "hpo id and name read from hp.obo; MedDRA terms matched from the vocabulary; MeSH unverified"
    return completed


def render(stamp: str, fine_rows: list[dict[str, str]], assignments: list[dict[str, str]], impc_rows: list[dict[str, str]]) -> str:
    coarse_count = len({row["coarse_symptom"] for row in fine_rows})
    lines = ["# The fine symptom constructs (generated by experiments/build_fine_symptom_crosswalk.py — do not edit by hand)", "", stamp, "",
             f"{len(fine_rows)} fine constructs from {coarse_count} coarse ones. A coarse construct with several HPO roots is split at those roots; each "
             "fine construct is named by its root's HPO name, so none is authored here. Merging is left to the model (decision 9.58).", "",
             "| fine construct | coarse construct | HPO root | MedDRA preferred terms |", "| --- | --- | --- | --- |"]
    for row in fine_rows:
        lines.append(f"| {row['target_symptom']} | {row['coarse_symptom']} | {row['hpo_ids']} {row['hpo_names']} | {row['meddra_preferred_terms'].replace(';', '; ')} |")
    lines += ["", "## How each MedDRA term of a split coarse construct was assigned", "",
              "`override` is a row of configs/fine_construct_term_overrides.csv; `hpo vocabulary` means the term's words are a name or synonym in the "
              "construct's HPO expansion; `stem match` means the term shares word stems with the root's own name or synonyms; `namesake` means nothing "
              "decided and the term went to the coarse construct's namesake root. Move any of them with an override.", "",
              "| coarse construct | term | fine construct | how |", "| --- | --- | --- | --- |"]
    for assignment in assignments:
        if assignment["how"] != "single construct":
            lines.append(f"| {assignment['coarse_symptom']} | {assignment['term']} | {assignment['fine_construct']} | {assignment['how']} |")
    by_how: dict[str, int] = {}
    for assignment in assignments:
        by_how[assignment["how"]] = by_how.get(assignment["how"], 0) + 1
    lines += ["", "Counts: " + ", ".join(f"{how} {count}" for how, count in sorted(by_how.items())) + ".", "",
              "## The IMPC crosswalk at the fine level", "",
              "| fine construct | relation | MP terms | validity |", "| --- | --- | --- | --- |"]
    for row in impc_rows:
        lines.append(f"| {row['target_symptom']} | {row['relation']} | {row['mp_term_names'] or '-'} | {row['validity']} |")
    lines.append("")
    return "\n".join(lines)


def build(obo: Path, sider: Path) -> tuple[list[dict[str, str]], list[dict[str, str]], list[dict[str, str]]]:
    vocabulary = HpoVocabulary.from_obo(obo)
    preferred_terms = meddra_preferred_terms(sider)
    coarse_rows = read_rows(COARSE_CROSSWALK_PATH)
    additions = [complete_addition(addition, vocabulary, preferred_terms) for addition in read_rows(ADDITIONS_PATH)] if ADDITIONS_PATH.exists() else []
    overrides = read_term_overrides(TERM_OVERRIDES_PATH)
    fine_rows, assignments = build_fine_crosswalk(coarse_rows, additions, overrides, vocabulary)
    impc_rows = fine_impc_rows(read_rows(IMPC_COARSE_PATH), coarse_rows, additions)
    return fine_rows, assignments, impc_rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--obo", type=Path, default=DEFAULT_OBO)
    parser.add_argument("--sider-side-effects", type=Path, default=DEFAULT_SIDER_SIDE_EFFECTS)
    parser.add_argument("--page", type=Path, default=DEFAULT_PAGE)
    parser.add_argument("--check", action="store_true", help="compare a fresh build with the committed files and change nothing")
    arguments = parser.parse_args()
    fine_rows, assignments, impc_rows = build(arguments.obo, arguments.sider_side_effects)
    if arguments.check:
        committed = read_rows(FINE_CROSSWALK_PATH) if FINE_CROSSWALK_PATH.exists() else []
        fresh = [{column: row.get(column, "") for column in FINE_COLUMNS} for row in fine_rows]
        committed = [{column: row.get(column, "") for column in FINE_COLUMNS} for row in committed]
        if fresh != committed:
            print(f"{FINE_CROSSWALK_PATH} differs from a fresh build; rerun without --check")
            return 1
        print(f"{FINE_CROSSWALK_PATH} is current")
        return 0
    write_rows(FINE_CROSSWALK_PATH, fine_rows, FINE_COLUMNS)
    write_rows(IMPC_FINE_PATH, impc_rows, IMPC_COLUMNS)
    stamp = provenance_stamp("experiments/build_fine_symptom_crosswalk.py", [str(COARSE_CROSSWALK_PATH), str(ADDITIONS_PATH), str(TERM_OVERRIDES_PATH), str(IMPC_COARSE_PATH), "hp.obo", "SIDER meddra_all_se"])
    arguments.page.write_text(render(stamp, fine_rows, assignments, impc_rows), encoding="utf-8")
    print(f"wrote {FINE_CROSSWALK_PATH} ({len(fine_rows)} constructs), {IMPC_FINE_PATH} ({len(impc_rows)} rows), {arguments.page}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Keep configs/documentation_registry.json in step with the documents git tracks (docs/documentation_process.md).

The register names every tracked Markdown document and its class (generated, living, record, frozen, draft), which
decides what tests/test_documentation_process.py checks for it. A document the register does not name fails the
suite, so this script is the way a new document gets in:

  python experiments/register_documents.py --add-missing      add an entry for every unregistered document, with the
                                                              class the header suggests and "confirmed": false; the
                                                              suite fails until a session sets the class and removes
                                                              the flag, so a guess never passes for a classification
  python experiments/register_documents.py --prune-missing    drop entries whose file git no longer tracks
  python experiments/register_documents.py --report           print the register as a table

How the class is guessed, for --add-missing only: a header that names the script that wrote the file is `generated`;
anything else is `living`, with the review fields set from the last commit that touched it, which is the one claim
about it the log supports.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from mechanistic_pathway_learning.documentation import (
    REGISTRY_PATH,
    REPOSITORY_ROOT,
    git_output,
    names_its_generator,
    sha256_of,
    unregistered_and_missing,
)

GENERATOR_IN_HEADER = re.compile(r"(?:generated by|written by|generated \d{4}-\d{2}-\d{2} by) `?(?P<script>(?:experiments|mechanistic_pathway_learning|scripts)/[A-Za-z0-9_./-]+\.py)`?", flags=re.IGNORECASE)


def generator_named_in(text: str) -> str | None:
    match = GENERATOR_IN_HEADER.search("\n".join(text.splitlines()[:6]))
    return match.group("script") if match else None


def last_commit(path: str) -> tuple[str, str]:
    """(short sha, date) of the last commit that touched the file."""
    logged = git_output("log", "-1", "--format=%h %ad", "--date=short", "--", path).split()
    return (logged[0], logged[1]) if len(logged) == 2 else ("", "")


def first_commit_date(path: str) -> str:
    dates = git_output("log", "--diff-filter=A", "--format=%ad", "--date=short", "--", path).split()
    return dates[-1] if dates else ""


def guessed_entry(path: str) -> dict:
    text = (REPOSITORY_ROOT / path).read_text(encoding="utf-8", errors="replace")
    generator = generator_named_in(text)
    if generator or names_its_generator(text, None):
        return {"class": "generated", "generator": generator or "unknown", "confirmed": False}
    commit, reviewed = last_commit(path)
    return {"class": "living", "reviewed": reviewed, "as_of_commit": commit, "confirmed": False}


def load() -> dict:
    return json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))


def save(registry: dict) -> None:
    registry["documents"] = dict(sorted(registry["documents"].items()))
    REGISTRY_PATH.write_text(json.dumps(registry, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def report(registry: dict) -> str:
    lines = [f"{'path':62s} {'class':10s} detail"]
    for path, entry in registry["documents"].items():
        detail = entry.get("generator") or (f"reviewed {entry.get('reviewed')} at {entry.get('as_of_commit')}" if entry["class"] == "living" else "")
        if entry["class"] == "record":
            detail = f"recorded {entry.get('recorded', '?')}" + (", append-only" if entry.get("append_only") else "")
        if entry["class"] == "frozen":
            detail = f"sha256 {entry.get('sha256', '')[:16]}"
        flag = "  (unconfirmed)" if entry.get("confirmed") is False else ""
        lines.append(f"{path:62s} {entry['class']:10s} {detail}{flag}")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--add-missing", action="store_true")
    parser.add_argument("--prune-missing", action="store_true")
    parser.add_argument("--report", action="store_true")
    parser.add_argument("--refresh-frozen-hashes", action="store_true", help="recompute the sha256 of every frozen document; only for a deliberate re-freeze")
    arguments = parser.parse_args()
    registry = load()
    from mechanistic_pathway_learning.documentation import load_registry
    unregistered, missing = unregistered_and_missing(load_registry())
    changed = False
    if arguments.add_missing:
        for path in unregistered:
            registry["documents"][path] = guessed_entry(path)
            print(f"added {path} as {registry['documents'][path]['class']} (unconfirmed)")
            changed = True
    if arguments.prune_missing:
        for path in missing:
            del registry["documents"][path]
            print(f"dropped {path}: not tracked")
            changed = True
    if arguments.refresh_frozen_hashes:
        for path, entry in registry["documents"].items():
            if entry["class"] == "frozen":
                entry["sha256"] = sha256_of(REPOSITORY_ROOT / path)
                print(f"{path}: sha256 {entry['sha256']}")
                changed = True
    if changed:
        save(registry)
    if arguments.report or not changed:
        print(report(registry))
        if unregistered and not arguments.add_missing:
            print(f"\nunregistered: {', '.join(unregistered)}")
        if missing and not arguments.prune_missing:
            print(f"\nregistered but not tracked: {', '.join(missing)}")
    return 0 if not (unregistered and not arguments.add_missing) else 1


if __name__ == "__main__":
    sys.exit(main())

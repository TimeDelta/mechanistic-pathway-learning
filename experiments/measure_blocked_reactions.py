"""Count the Human-GEM reactions that cannot carry flux, and what removing them would take out of the slice graph.

A label-free candidate for paring the graph (the user's direction of 7 October 2026: pare the graph to useful nodes
so that new layers add less noise). A reaction is blocked when flux variability analysis gives it zero minimum and
maximum flux with every boundary reaction open in both directions, the most permissive medium, so a reaction blocked
here is blocked under any medium. Such a reaction carries no steady-state flux, and a metabolite or gene whose every
reaction is blocked is a dead end for any mechanism that runs through flux. This script removes nothing; it reports
the counts and the slice perturbation genes the cut would reach, with their positive pairs, so the cut can be judged
before it is made.

The blocked set is cached in runs/paring/blocked_reactions.json, so a rerun reads it instead of repeating the
analysis.

Usage: python experiments/measure_blocked_reactions.py [--output docs/blocked_reactions.md]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from mechanistic_pathway_learning.evaluation.experiment_data import load_experiment_data

ANCHOR_GENES = ("PAH", "OTC", "CPS1", "CBS", "MTHFR", "GCH1", "TH", "DDC", "DBH", "MAOA", "COMT", "SLC6A3", "SLC18A2", "GAD1",
                "ALDH5A1", "ABAT", "ATP1A3", "SLC12A5")


def blocked_reactions(model_path: Path, cache_path: Path) -> list[str]:
    if cache_path.exists():
        return json.loads(cache_path.read_text())
    from cobra.flux_analysis import find_blocked_reactions
    from cobra.io import read_sbml_model

    model = read_sbml_model(str(model_path))
    blocked = sorted(find_blocked_reactions(model, open_exchanges=True, processes=1))
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache_path.write_text(json.dumps(blocked))
    return blocked


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model", type=Path, default=Path("data/raw/Human-GEM/model/Human-GEM.xml"))
    parser.add_argument("--graph-dir", type=Path, default=Path("data/processed/graph"))
    parser.add_argument("--evidence-dir", type=Path, default=Path("data/processed/evidence"))
    parser.add_argument("--cache", type=Path, default=Path("runs/paring/blocked_reactions.json"))
    parser.add_argument("--output", type=Path, default=Path("docs/blocked_reactions.md"))
    arguments = parser.parse_args()

    blocked = set(blocked_reactions(arguments.model, arguments.cache))
    nodes = pd.read_parquet(arguments.graph_dir / "nodes.parquet")
    edges = pd.read_parquet(arguments.graph_dir / "edges.parquet")
    reactions = set(nodes.node_id[nodes.node_type == "reaction"])
    blocked_in_graph = blocked & reactions
    reaction_side = np.where(edges.source_id.isin(reactions), edges.source_id, edges.target_id)
    other_side = np.where(edges.source_id.isin(reactions), edges.target_id, edges.source_id)
    incident = pd.DataFrame({"reaction": reaction_side, "partner": other_side, "relation": edges.relation_type.values})
    incident = incident[incident.reaction.isin(reactions)]
    incident["blocked"] = incident.reaction.isin(blocked_in_graph)
    share_blocked_by_partner = incident.groupby("partner")["blocked"].mean()
    node_type = nodes.set_index("node_id").node_type
    dead_partners = share_blocked_by_partner[share_blocked_by_partner == 1.0].index
    dead_metabolites = [partner for partner in dead_partners if node_type.get(partner) == "metabolite"]
    dead_genes = {partner for partner in dead_partners if node_type.get(partner) == "gene"}

    data = load_experiment_data(arguments.graph_dir, arguments.evidence_dir, group_by="disease_cluster")
    outcomes = data.outcomes >= 0.5
    gene_share = {gene: share_blocked_by_partner.get(f"GENE:{gene}", np.nan) for gene in data.perturbation_ids}
    all_blocked_genes = [gene for gene, share in gene_share.items() if share == 1.0]
    some_blocked_genes = [gene for gene, share in gene_share.items() if 0.0 < share < 1.0]
    row_of = {gene: index for index, gene in enumerate(data.perturbation_ids)}

    lines = [
        "# Reactions that cannot carry flux (generated by experiments/measure_blocked_reactions.py)",
        "",
        f"Flux variability analysis of {arguments.model} with every boundary reaction open in both directions; a reaction is "
        "blocked when its minimum and maximum flux are both zero. Nothing is removed here.",
        "",
        "| quantity | count |",
        "|---|---|",
        f"| reactions in the model reported blocked | {len(blocked)} |",
        f"| reaction nodes in {arguments.graph_dir} | {len(reactions)} |",
        f"| of them blocked | {len(blocked_in_graph)} ({len(blocked_in_graph) / len(reactions):.1%}) |",
        f"| metabolites whose every reaction is blocked | {len(dead_metabolites)} of {int((nodes.node_type == 'metabolite').sum())} |",
        f"| genes whose every reaction is blocked | {len(dead_genes)} of {int((nodes.node_type == 'gene').sum())} |",
        f"| slice perturbation genes whose every reaction is blocked | {len(all_blocked_genes)} of {len(data.perturbation_ids)}, "
        f"{int(sum(outcomes[row_of[gene]].sum() for gene in all_blocked_genes))} of {int(outcomes.sum())} positive pairs |",
        f"| slice perturbation genes with some reactions blocked | {len(some_blocked_genes)} |",
        "",
        "| anchor gene | share of its reactions blocked | positive pairs |",
        "|---|---|---|",
    ]
    for gene in ANCHOR_GENES:
        if gene in row_of:
            share = gene_share[gene]
            lines.append(f"| {gene} | {'no reactions' if np.isnan(share) else f'{share:.2f}'} | {int(outcomes[row_of[gene]].sum())} |")
    lines += ["", "Slice perturbation genes whose every reaction is blocked: " + (", ".join(sorted(all_blocked_genes)) or "none") + ".", ""]
    arguments.output.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()

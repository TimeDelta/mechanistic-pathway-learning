CARD_FAMILY = re.compile(r"^docs/mechanism_cards/([^/]+)/[^/]+\.md$")
GENERATED_SUFFIX = re.compile(r"\s*\((generated|written)\b[^)]*\)\s*$")


def document_title(path: Path) -> str:
    """The first level-one heading, without the "(generated by ... do not edit by hand)" it may end with."""
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return GENERATED_SUFFIX.sub("", line[2:].strip()) or path.name
    except OSError:
        pass
    return path.name


def topic_of(path: str) -> str:
    for topic, patterns in TOPICS:
        if any(fnmatch.fnmatch(path, pattern) for pattern in patterns):
            return topic
    return OTHER_TOPIC


def link(path: str) -> str:
    """A link from docs/README.md to a repository path."""
    return path[len("docs/"):] if path.startswith("docs/") else f"../{path}"


def render_index(stamp: str, root: Path = REPOSITORY_ROOT) -> str:
    registry = load_registry(root / "configs" / "documentation_registry.json")
    own_path = str(INDEX_PATH.relative_to(REPOSITORY_ROOT))
    entries = {path: document for path, document in registry.items() if path != own_path}
    missing_start = [path for path, _, _ in START_HERE if path not in entries]
    if missing_start:
        raise ValueError(f"START_HERE names unregistered documents: {missing_start}")
    lines = [TITLE, "", stamp, "",
             "This project builds a signed, typed physiology graph (genes and the proteins they encode, metabolites and reactions, signalling, "
             "transcription, electrical and drug-mechanism layers, brain cell classes) and models how a perturbation, an allele of a gene or a drug, "
             "propagates through it to psychiatric symptom constructs, so that the learned mechanisms can serve as the basis of a new psychiatric "
             "nosology. The [repository README](../README.md) is the overview; this page is the map of the documents.",
             "",
             "Each document has a class, which says how far to trust it as a statement of the present "
             "([documentation process](documentation_process.md)): **living** documents are kept current and reviewed; **records** are dated and "
             "corrected only by dated additions; **generated** documents are written by the script they name and carry its stamp; **frozen** "
             "documents are pinned by their hash; **drafts** await the owner. What is current is in [status](status.md), not in memory.",
             "", "## Start here", ""]
    for path, label, reason in START_HERE:
        lines.append(f"- [{label}]({link(path)}): {reason}")
    grouped: dict[str, list[str]] = defaultdict(list)
    for path in sorted(entries):
        grouped[topic_of(path)].append(path)
    for topic in [name for name, _ in TOPICS] + [OTHER_TOPIC]:
        paths = grouped.get(topic, [])
        if not paths:
            continue
        lines += ["", f"## {topic}", ""]
        families: dict[str, list[str]] = defaultdict(list)
        listed = []
        for path in paths:
            family = CARD_FAMILY.match(path)
            if family:
                families[family.group(1)].append(path)
            else:
                listed.append(path)
        # hand-written documents before generated ones, each set by title
        order = {"living": 0, "record": 1, "draft": 2, "frozen": 3, "generated": 4}
        for path in sorted(listed, key=lambda name: (order.get(entries[name].document_class, 5), document_title(root / name).lower())):
            document = entries[path]
            what = document.fields.get("what")
            if document.document_class == "frozen":
                what = f"the copy frozen on {document.fields.get('frozen_on', 'its date')}, pinned by its SHA-256"
            suffix = f": {what.rstrip('.')}" if what else ""
            lines.append(f"- [{document_title(root / path)}]({link(path)}) ({CLASS_LABELS[document.document_class]}){suffix}.")
        for family, members in sorted(families.items()):
            cards = ", ".join(f"[{Path(member).stem.replace('_', ' ')}]({link(member)})" for member in sorted(members))
            lines.append(f"- Mechanism cards of the run `{family}` (generated), one per symptom: {cards}.")
    lines.append("")
    return "\n".join(lines)


def without_stamp(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.startswith("Generated by `"))


def index_is_current(committed: str, rendered: str) -> bool:
    """Equal apart from the stamp, whose date and commit change with every run."""
    return without_stamp(committed) == without_stamp(rendered)


def rendered_index() -> str:
    return render_index(provenance_stamp(GENERATOR, STAMP_INPUTS))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    rendered = rendered_index()
    if arguments.check:
        if not INDEX_PATH.exists() or not index_is_current(INDEX_PATH.read_text(encoding="utf-8"), rendered):
            print("out of date: docs/README.md; run experiments/generate_docs_index.py (experiments/generate_status.py runs it)")
            return 1
        print("docs/README.md is current")
        return 0
    INDEX_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {INDEX_PATH.relative_to(REPOSITORY_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Calibrating the placeholder concentration against the measured one, so a drug without pharmacokinetics keeps an
occupancy rather than losing it.

The owner, 13 October 2026: "i don't want it to throw out the existing occupancies just because they can't be
calculated by that method. It should look at disagreements between the sources and take the mean or median
disagreement as an offset to the existing occupancy of that drug if it can't be calculated."

That is a calibration transfer and it is the right instrument: estimate the systematic disagreement between the two
sources on the drugs where both exist, and carry it to the drugs where only one does. This script estimates it.

**The offset is applied to the concentration, not to the occupancy.** Occupancy is bounded in [0, 1] and saturating,
so an additive offset on it is ill-defined near either end and can leave the interval; and the disagreement is not
really about occupancy at all, but about the concentration the two methods assume. occupancy = C / (C + Kd), so a
correction on log C respects the bound by construction and sits where the disagreement actually is. The placeholder
scheme fixes the best-bound mechanism target at 0.9 occupancy, which is the same as asserting C = 9 * Kd for that
target; the measured scheme reads an unbound concentration at each target's own site. Both are inverted back to a
concentration here and compared in log10.

Counting only: no label, table, graph or model input is changed.

Usage:
  python experiments/label_review/placeholder_concentration_calibration.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

OCCUPANCY_TABLE = Path("data/processed/exposure/target_occupancy_v4.csv")
PLACEHOLDER_OCCUPANCY_OF_THE_BEST_TARGET = 0.9
OCCUPANCY_CLIP = 1e-9


def concentration_from_occupancy(occupancy: pd.Series, dissociation_constant: pd.Series) -> pd.Series:
    """Invert occupancy = C / (C + Kd). The clip keeps a reading of exactly 0 or 1 from giving 0 or infinity."""
    clipped = occupancy.clip(OCCUPANCY_CLIP, 1 - OCCUPANCY_CLIP)
    return dissociation_constant * clipped / (1 - clipped)


def per_drug_concentrations(occupancy_table: pd.DataFrame) -> pd.DataFrame:
    """Per drug: the placeholder concentration, and the low and high ends of the measured one."""
    site = occupancy_table[occupancy_table.at_the_target_s_own_site].copy()
    site["dissociation_constant"] = 10 ** (-site.p_affinity)
    site["c_low"] = concentration_from_occupancy(site.occupancy_low, site.dissociation_constant)
    site["c_high"] = concentration_from_occupancy(site.occupancy_high, site.dissociation_constant)
    best_mechanism_affinity = site[site.role == "mechanism"].groupby("perturbation_id").p_affinity.max()
    placeholder_ratio = PLACEHOLDER_OCCUPANCY_OF_THE_BEST_TARGET / (1 - PLACEHOLDER_OCCUPANCY_OF_THE_BEST_TARGET)
    site["placeholder"] = site.perturbation_id.map(placeholder_ratio * 10 ** (-best_mechanism_affinity))
    usable = site[site.placeholder.notna() & site.c_low.notna() & site.c_high.notna()]
    return usable.groupby("perturbation_id").agg(placeholder=("placeholder", "first"),
                                                 low=("c_low", "median"), high=("c_high", "median"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--occupancy-table", type=Path, default=OCCUPANCY_TABLE)
    parser.add_argument("--markdown-output", type=Path)
    arguments = parser.parse_args()

    per_drug = per_drug_concentrations(pd.read_csv(arguments.occupancy_table))
    centre = np.sqrt(per_drug.low * per_drug.high)
    offset = np.log10(per_drug.placeholder / centre)
    corrected = per_drug.placeholder / 10 ** offset.median()
    inside = lambda column: ((column >= per_drug.low) & (column <= per_drug.high)).mean()

    lines = ["# Calibrating the placeholder concentration against the measured one", "",
             "Generated by `experiments/label_review/placeholder_concentration_calibration.py`.", "",
             f"Estimated on the **{len(per_drug)} drugs** that have both a placeholder and a measured concentration, "
             "comparing each against the geometric centre of its measured therapeutic range, in log10.", "",
             "| reading | value |", "|---|---|",
             f"| median offset | **{offset.median():+.3f} log10**, so the placeholder overstates the concentration by **{10 ** offset.median():.1f}x** |",
             f"| mean offset | {offset.mean():+.3f} log10 |",
             f"| scatter about it | sd **{offset.std():.2f} log10**, quartiles {offset.quantile(.25):+.2f} to {offset.quantile(.75):+.2f} |",
             f"| drugs landing inside the measured range, before | {inside(per_drug.placeholder):.0%} |",
             f"| drugs landing inside the measured range, after | {inside(corrected):.0%} |",
             f"| median absolute log10 error against the range centre, before | {np.abs(np.log10(per_drug.placeholder / centre)).median():.2f} |",
             f"| median absolute log10 error against the range centre, after | {np.abs(np.log10(corrected / centre)).median():.2f} |", "",
             "## What this says", "",
             f"**The offset is real and worth taking.** The placeholder sits {10 ** offset.median():.1f} times above the centre of the "
             "measured range, a systematic bias that costs nothing to remove and that nobody would want left in.", "",
             "**It does not make an imputed concentration a measured one.** The scatter about the offset is "
             f"{offset.std():.2f} log units, about two orders of magnitude of drug-to-drug disagreement, and no single "
             f"offset touches it: correcting moves the drugs landing inside their own measured range from "
             f"{inside(per_drug.placeholder):.0%} to {inside(corrected):.0%}, and the median error from "
             f"{np.abs(np.log10(per_drug.placeholder / centre)).median():.2f} to {np.abs(np.log10(corrected / centre)).median():.2f} log units. "
             "The bias is what a calibration removes; the scatter is what it cannot.", "",
             "**So the offset belongs with a flag, not instead of one.** An imputed occupancy carries roughly a "
             "ten-fold uncertainty in the concentration behind it, which an occupancy near saturation or near zero "
             "absorbs and one near Kd does not. That is what the \"has a measured occupancy\" stratum is for, and the "
             "calibration does not remove the need for it.", "",
             "**One limit on the transfer.** The offset is estimated on the drugs that have a measured concentration, "
             "which are the better-studied ones, and applied to those that do not. If the placeholder's bias differs "
             "between the two, the correction does not carry. That is the same extrapolation this project registered "
             "for the Open Targets agreement, and it is stated rather than tested, because nothing measures it."]
    table = "\n".join(lines)
    print(table)
    if arguments.markdown_output:
        arguments.markdown_output.write_text(table + "\n")


if __name__ == "__main__":
    main()

"""What admitting off-targets costs under the mechanism-target split of preregistration item 25, and what requiring
a measured occupancy costs in coverage.

Two questions the owner put on 13 October 2026, both of which the earlier answer got wrong in the same way: it was
measured against the leakage-group drug split that item 25 replaced.

"For leakage, this no longer applies after the new split method, right?" Largely yes. The recorded objection -
admitting off-targets takes the largest leakage group from 71 to 203-209 of 222 drugs - is a property of the
group-based split, where two drugs sharing any target share a group, so promiscuous off-targets merge everything.
Item 25 does not group drugs: it partitions the targets and holds a drug out whole when any of its targets is in
the partition, solving for the target fraction that gives the registered held-out share. More targets per drug
means a smaller fraction solves it, which is what the construction is for. What off-targets do cost under item 25
is **novelty**, not size: a held-out drug shares more of its targets with the training side, so fewer of its
mechanisms are new, and the secondary stratum of item 25c - drugs none of whose targets is in training - shrinks.

"I think taking all with occupancy is better." That is a coverage question, and this script prices it: how many
drugs and how many kept positive pairs leave the study if a measured occupancy is required.

Counting only: no label, table, graph or model input is changed.

Usage:
  python experiments/label_review/off_targets_under_the_target_split.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from mechanistic_pathway_learning.evaluation.target_held_out_split import held_out_targets

OCCUPANCY_TABLE = Path("data/processed/exposure/target_occupancy_v4.csv")
OFF_TARGET_THRESHOLDS = (None, 0.25, 0.10)
DRAWS = 60


def targets_of_drug(site_rows: pd.DataFrame, admit_off_targets_above: float | None) -> dict[str, set[str]]:
    """Each drug's targets: its mechanism genes, plus any off-target occupied at or above the threshold."""
    rows = site_rows[site_rows.role == "mechanism"] if admit_off_targets_above is None else \
        site_rows[(site_rows.role == "mechanism") | (site_rows.occupancy_high >= admit_off_targets_above)]
    return rows.groupby("perturbation_id").gene.apply(set).to_dict()


def split_readings(targets: dict[str, set[str]], draws: int) -> dict[str, float]:
    """Over redraws of the item 25 split: the held-out share, and how novel a held-out drug's mechanisms are."""
    num_targets = len({gene for genes in targets.values() for gene in genes})
    shares, fractions, novelty, wholly_new = [], [], [], []
    for seed in range(draws):
        held = held_out_targets(targets, seed)
        held_drugs = [drug for drug, genes in targets.items() if genes & held]
        trained = {gene for drug, genes in targets.items() if drug not in held_drugs for gene in genes}
        new_per_drug = [len(targets[drug] - trained) / len(targets[drug]) for drug in held_drugs]
        shares.append(len(held_drugs) / len(targets))
        fractions.append(len(held) / num_targets)
        novelty.append(np.mean(new_per_drug) if new_per_drug else np.nan)
        wholly_new.append(np.mean([share == 1.0 for share in new_per_drug]) if new_per_drug else np.nan)
    return {"drugs": len(targets), "targets": num_targets,
            "targets_per_drug": float(np.mean([len(genes) for genes in targets.values()])),
            "held_out_share": float(np.mean(shares)), "held_out_share_sd": float(np.std(shares)),
            "target_fraction": float(np.mean(fractions)),
            "unseen_share_of_a_held_out_drugs_targets": float(np.nanmean(novelty)),
            "held_out_drugs_with_no_target_in_training": float(np.nanmean(wholly_new))}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--occupancy-table", type=Path, default=OCCUPANCY_TABLE)
    parser.add_argument("--evidence-dir", type=Path, default=Path("data/processed/evidence_full_v4"))
    parser.add_argument("--label-selection", type=Path, default=Path("data/processed/label_selection/better_v2_full_v4.parquet"))
    parser.add_argument("--draws", type=int, default=DRAWS)
    parser.add_argument("--markdown-output", type=Path)
    arguments = parser.parse_args()

    occupancy = pd.read_csv(arguments.occupancy_table)
    site_rows = occupancy[occupancy.at_the_target_s_own_site]
    lines = ["# Off-targets under the item 25 split, and the cost of requiring a measured occupancy",
             "", "Generated by `experiments/label_review/off_targets_under_the_target_split.py`.", "",
             "> **This is a sensitivity reading of an alternative the registration declined, not an open "
             "question.** Preregistration item 25 splits the held-out set on **mechanism targets** and reports "
             "off-target sharing through its secondary stratum 25c; off-targets appear nowhere in item 25. The "
             "table below asks what admitting them to the split would have cost. Its \"threshold\" is therefore "
             "hypothetical: there is no registered threshold, and none is wanted, because all off-targets enter "
             "the **model input** at their occupancy (item 5c step 1), where an engagement near zero contributes "
             "near zero on its own. On 13 October 2026 this document's threshold language was promoted into an "
             "open decision for the owner, who corrected it: \"I thought we already settled on option three\". "
             "Do not read a decision out of this file.", "",
             "## The split holds its size and loses novelty", "",
             "| off-targets admitted | drugs | targets | targets per drug | held-out drugs | target fraction solved for | unseen share of a held-out drug's targets | held-out drugs with no target in training |",
             "|---|---|---|---|---|---|---|---|"]
    for threshold in OFF_TARGET_THRESHOLDS:
        reading = split_readings(targets_of_drug(site_rows, threshold), arguments.draws)
        label = "none (mechanism only)" if threshold is None else f"occupancy >= {threshold}"
        lines.append(f"| {label} | {reading['drugs']} | {reading['targets']} | {reading['targets_per_drug']:.1f} | "
                     f"{reading['held_out_share']:.1%} (sd {reading['held_out_share_sd']:.1%}) | {reading['target_fraction']:.2%} | "
                     f"{reading['unseen_share_of_a_held_out_drugs_targets']:.1%} | "
                     f"{reading['held_out_drugs_with_no_target_in_training']:.1%} |")
    lines += ["",
              "**Every row of that table is measured on the drugs the occupancy table covers, not on the study.** "
              "The occupancy table holds only the drugs with a measured concentration, so the mechanism-only row "
              "stands on 115 drugs and 75 targets where item 25's registered split stands on 222 drugs and 192 "
              "targets. The last column is the same quantity as item 25c's secondary stratum and the two numbers "
              "differ for that reason alone: **38.6 percent here against the 21.2 percent item 25c registers**, "
              "which is the full table. So this table prices the **shape** of the trade - admit weaker engagements "
              "as targets and a held-out drug shares more of them with training - and not the levels the study will "
              "see. The levels move at the v4 rebuild, which lifts item 1's three-target limit and so changes every "
              "drug's target set. A threshold chosen on these numbers should be chosen for the shape."]

    records = pd.read_parquet(arguments.evidence_dir / "evidence_records.parquet")
    selection = pd.read_parquet(arguments.label_selection)
    kept = selection[selection.keep]
    drugs = set(records[records.perturbation_type == "drug"].perturbation_id)
    with_occupancy = set(occupancy.perturbation_id) & drugs
    kept_drug_pairs = kept[kept.perturbation_id.isin(drugs)]
    covered = int(kept_drug_pairs.perturbation_id.isin(with_occupancy).sum())
    labels = records[records.perturbation_type == "drug"].drop_duplicates("perturbation_id").set_index("perturbation_id").perturbation_label
    dropped = sorted(labels.get(drug, drug) for drug in drugs - with_occupancy)
    lines += ["", "## What requiring a measured occupancy costs", "",
              f"- drugs with a reading: **{len(with_occupancy)}** of {len(drugs)}; without: **{len(drugs) - len(with_occupancy)}**",
              f"- kept positive drug pairs carried by drugs with a reading: **{covered}** of {len(kept_drug_pairs)} "
              f"({covered / len(kept_drug_pairs):.1%}); the rest, **{1 - covered / len(kept_drug_pairs):.1%}**, leaves with them",
              "", "The missingness is not random. A drug needs a published therapeutic range and a fraction unbound, "
              "which newer drugs are least likely to have, so the drugs that leave skew modern and include a good deal "
              "of the pharmacology a psychiatric study is for:", "",
              "  " + ", ".join(dropped[:30]) + (", ..." if len(dropped) > 30 else "")]
    table = "\n".join(lines)
    print(table)
    if arguments.markdown_output:
        arguments.markdown_output.write_text(table + "\n")


if __name__ == "__main__":
    main()

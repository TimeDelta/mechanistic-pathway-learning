"""Descriptors for the Reactome protein entities of a graph, from the entity's own annotation vector projected onto the
directions the protein descriptors use (mechanistic_pathway_learning/graph/complex_descriptors.py).

The reduced-rank regression is refitted at the penalty and rank recorded in protein_descriptor_fit.json, which gives
the annotation-space directions V_k that experiments/build_protein_descriptors.py keeps only in composition with the
embedding coefficients. The sign of a direction is not fixed by the fit, so each column takes the sign of the stored
protein table's, as the per-entry descriptors do, and the refit must reproduce that table before anything is written.

Outputs: data/processed/node_descriptors/complex_descriptors.parquet (node_id by rrr_1 ... rrr_k) and
docs/complex_descriptors.md. Nothing else is changed; wiring the table into a graph's node_descriptors.parquet is
experiments/build_node_descriptors.py --complex-descriptors.

    OMP_NUM_THREADS=2 PYTHONPATH=. python experiments/build_complex_descriptors.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from mechanistic_pathway_learning.graph.complex_descriptors import (PROTEIN_ENTITY_TYPE, SET_KINDS, entity_annotation_rows,
                                                                    member_genes_of_entity, standardise_with_proteome_statistics)
from mechanistic_pathway_learning.graph.protein_descriptors import (ReducedRankRegression, annotation_target_matrix, go_annotations,
                                                                    read_go_ancestors, ridge_coefficients, top_target_directions,
                                                                    weighted_standardised_targets)
from mechanistic_pathway_learning.graph.reactome_import import parse_reactome_sbml
from experiments.build_protein_descriptors import PER_GENE_REPRODUCTION_TOLERANCE, load_embeddings


def entity_kinds(reactome_dir: Path) -> dict[str, str]:
    """Protein entity node id -> the Reactome entity class (Complex, DefinedSet, CandidateSet, ...)."""
    kinds = {}
    for path in sorted(reactome_dir.glob("*.sbml")):
        species, _ = parse_reactome_sbml(path.read_text())
        for species_id, entity in species.items():
            kinds[f"RCTE_{species_id.split('_')[-1]}"] = entity.kind
    return kinds


def fitted_model_and_directions(embeddings: pd.DataFrame, accessions: pd.Series, target_values: np.ndarray, fit_rows: np.ndarray,
                                rank: int, relative_alpha: float) -> tuple[ReducedRankRegression, np.ndarray]:
    """The same fit as graph/protein_descriptors.fit_reduced_rank_regression, with its annotation-space directions
    V_k [number of targets, rank] returned beside the model."""
    fit_embeddings = embeddings.loc[accessions[fit_rows]].to_numpy(dtype=np.float64)
    mean = fit_embeddings.mean(axis=0)
    scale = np.where(fit_embeddings.std(axis=0) > 0, fit_embeddings.std(axis=0), 1.0)
    standardised = (fit_embeddings - mean) / scale
    coefficients = ridge_coefficients(standardised, target_values[fit_rows], relative_alpha * len(fit_embeddings))
    directions = top_target_directions(standardised, coefficients, rank)
    projection = coefficients @ directions
    scores = standardised @ projection
    model = ReducedRankRegression(mean, scale, projection, scores.mean(axis=0), np.where(scores.std(axis=0) > 0, scores.std(axis=0), 1.0))
    return model, directions


def protein_entity_nodes(graph_dirs: list[Path]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """The protein entity nodes of every graph directory given, and the member_of edges that reach them."""
    node_frames, edge_frames = [], []
    for graph_dir in graph_dirs:
        if not (graph_dir / "nodes.parquet").exists():
            continue
        nodes = pd.read_parquet(graph_dir / "nodes.parquet", columns=["node_id", "node_type", "display_name"])
        node_frames.append(nodes[nodes.node_type == PROTEIN_ENTITY_TYPE])
        edge_frames.append(pd.read_parquet(graph_dir / "edges.parquet", columns=["source_id", "target_id", "relation_type"]))
    nodes = pd.concat(node_frames, ignore_index=True).drop_duplicates("node_id") if node_frames else pd.DataFrame()
    edges = pd.concat(edge_frames, ignore_index=True).drop_duplicates() if edge_frames else pd.DataFrame()
    return nodes, edges


def markdown_report(result: dict) -> str:
    lines = ["# Descriptors for the Reactome protein entities", "",
             "Generated by experiments/build_complex_descriptors.py. The method and the reasoning behind the union and "
             "intersection rules are in mechanistic_pathway_learning/graph/complex_descriptors.py; the decision is the "
             "user's of 9 October 2026 (\"I like the separate annotation vector much better for the complexes\").", "",
             "## What was built", "",
             f"- protein entity nodes over {', '.join(result['graph_dirs'])}: {result['num_entities']}",
             f"- entities with at least one member gene: {result['num_entities_with_members']}",
             f"- entities with a descriptor (a member whose annotations are known): {result['num_entities_with_a_descriptor']}",
             f"- members per entity: median {result['members_per_entity']['median']}, maximum {result['members_per_entity']['max']}",
             f"- rank {result['rank']}, ridge penalty {result['relative_alpha']}, {result['num_targets']} annotation columns, "
             f"refit over {result['proteins_in_fit']} proteins", ""]
    lines += ["By Reactome entity class:", "", "| class | entities | with a descriptor | aggregation |", "|---|---|---|---|"]
    for kind, counts in result["by_entity_class"].items():
        rule = "mean over members (a disjunction)" if kind in SET_KINDS else "union or intersection by block"
        lines.append(f"| {kind} | {counts['entities']} | {counts['with_a_descriptor']} | {rule} |")
    lines += ["", "## Is an entity vector comparable with a protein descriptor?", "",
              "A protein's descriptor is the projection of the annotations *predicted from its sequence*; an entity's is "
              "the projection of annotations that are *recorded*. The two are different quantities, so the comparability "
              "is measured rather than assumed. Over the reviewed proteome, correlation between the two projections of "
              f"the same protein: median {result['observed_against_fitted_projection']['median_correlation']:.3f} per component "
              f"(minimum {result['observed_against_fitted_projection']['minimum_correlation']:.3f}, "
              f"maximum {result['observed_against_fitted_projection']['maximum_correlation']:.3f}), and "
              f"{result['observed_against_fitted_projection']['components_above_0_5']} of {result['rank']} components above 0.5.", "",
              f"For the {result['single_member_entities']['count']} entities with exactly one member gene, the entity vector "
              "should resemble that gene's protein descriptor; the median correlation across those entities is "
              f"{result['single_member_entities']['median_correlation_with_the_member_descriptor']:.3f}.", "",
              "Reading: the entity vectors share the protein descriptors' directions and units, but they are the observed-"
              "annotation projection, so they belong in their own block unless that correlation is high enough to justify "
              "one shared mapping.", "",
              "## Entities without a descriptor", "",
              f"{result['num_entities'] - result['num_entities_with_a_descriptor']} entities get none: "
              f"{result['num_entities'] - result['num_entities_with_members']} have no member gene (small-molecule-only, "
              "polymer or unmapped entities) and "
              f"{result['num_entities_with_members'] - result['num_entities_with_a_descriptor']} have member genes whose "
              "annotations are not in the reviewed table. They keep a zero block and a flag column, as a gene without "
              "protein descriptors does.", ""]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--uniprot-table", type=Path, default=Path("data/raw/uniprot/uniprot_human_reviewed.tsv.gz"))
    parser.add_argument("--gaf", type=Path, default=Path("data/raw/gene_ontology/goa_human.gaf.gz"))
    parser.add_argument("--go-obo", type=Path, default=Path("data/raw/gene_ontology/go-basic.obo"))
    parser.add_argument("--embedding-dir", type=Path, default=Path("data/processed/protein_embeddings"))
    parser.add_argument("--reactome-dir", type=Path, default=Path("data/raw/reactome/v97"))
    parser.add_argument("--graph-dirs", type=Path, nargs="+",
                        default=[Path("data/processed/graph_full_neuronal"), Path("data/processed/graph_full_neuronal_split")])
    parser.add_argument("--output-dir", type=Path, default=Path("data/processed/node_descriptors"))
    parser.add_argument("--report", type=Path, default=Path("docs/complex_descriptors.md"))
    arguments = parser.parse_args()

    recorded = json.loads((arguments.output_dir / "protein_descriptor_fit.json").read_text())
    uniprot = pd.read_csv(arguments.uniprot_table, sep="\t")
    embeddings = load_embeddings(arguments.embedding_dir)
    uniprot = uniprot[uniprot.Entry.isin(embeddings.index)].reset_index(drop=True)
    targets, block_columns, observed = annotation_target_matrix(uniprot, go_annotations(arguments.gaf, read_go_ancestors(arguments.go_obo)))
    target_values = weighted_standardised_targets(targets, block_columns, observed)
    fit_rows = (observed["go_function"] | observed["go_component"]).to_numpy()
    if int(fit_rows.sum()) != recorded["proteins_in_fit"] or targets.shape[1] != recorded["targets"]:
        raise SystemExit("the fit inputs differ from the recorded fit")

    model, directions = fitted_model_and_directions(embeddings, uniprot.Entry, target_values, fit_rows, recorded["rank"], recorded["relative_alpha"])
    descriptor_columns = [f"rrr_{index + 1}" for index in range(recorded["rank"])]
    fitted = pd.DataFrame(model.transform(embeddings.loc[uniprot.Entry].to_numpy(dtype=np.float64)), index=pd.Index(uniprot.Entry, name="accession"),
                          columns=descriptor_columns)
    gene_of_accession = uniprot.set_index("Entry")["Gene Names (primary)"]
    stored = pd.read_parquet(arguments.output_dir / "protein_descriptors.parquet")
    per_gene = fitted.groupby(gene_of_accession.reindex(fitted.index).to_numpy()).mean().reindex(stored.index)[stored.columns]
    column_signs = np.sign([np.corrcoef(per_gene[column], stored[column])[0, 1] for column in stored.columns])
    difference = float((per_gene * column_signs - stored).abs().to_numpy().max())
    if difference > PER_GENE_REPRODUCTION_TOLERANCE:
        raise SystemExit(f"the refit does not reproduce protein_descriptors.parquet (up to {difference:.3g}); nothing written")
    directions = directions * column_signs  # the stored table's signs, so an entity column means what the protein column means
    fitted = fitted[stored.columns] * column_signs

    # the proteins' own observed annotations through the same directions: the statistics the entities are standardised by
    protein_observed_scores = target_values @ directions
    reference_mean = protein_observed_scores[fit_rows].mean(axis=0)
    reference_scale = np.where(protein_observed_scores[fit_rows].std(axis=0) > 0, protein_observed_scores[fit_rows].std(axis=0), 1.0)
    standardised_protein_observed = (protein_observed_scores - reference_mean) / reference_scale
    correlations = [float(np.corrcoef(standardised_protein_observed[:, index], fitted.iloc[:, index])[0, 1]) for index in range(recorded["rank"])]

    nodes, edges = protein_entity_nodes(list(arguments.graph_dirs))
    kind_of_entity = entity_kinds(arguments.reactome_dir)
    member_genes = member_genes_of_entity(edges, nodes.node_id)
    gene_targets = targets.groupby(gene_of_accession.reindex(targets.index).to_numpy()).max()
    gene_observed = observed.groupby(gene_of_accession.reindex(observed.index).to_numpy()).any()
    assert list(gene_targets.index) == list(gene_observed.index), "the gene-level annotation and observation tables must share their row order"
    members_of_entity = {entity: [gene for gene in genes if gene in gene_targets.index] for entity, genes in member_genes.items()}
    entity_values, entity_annotated = entity_annotation_rows(members_of_entity, kind_of_entity, gene_targets, gene_observed, block_columns)
    standardised_entities = standardise_with_proteome_statistics(entity_values, entity_annotated, targets, observed, block_columns)
    entity_scores = (standardised_entities @ directions - reference_mean) / reference_scale
    entity_descriptors = pd.DataFrame(entity_scores, index=entity_values.index, columns=list(stored.columns))

    single_member = [entity for entity, genes in members_of_entity.items() if len(genes) == 1 and entity in entity_descriptors.index]
    single_member_correlations = []
    for entity in single_member:
        gene = members_of_entity[entity][0]
        if gene in stored.index:
            single_member_correlations.append(float(np.corrcoef(entity_descriptors.loc[entity].to_numpy(), stored.loc[gene].to_numpy())[0, 1]))
    member_counts = np.array([len(genes) for genes in member_genes.values()]) if member_genes else np.array([0])
    by_entity_class: dict[str, dict[str, int]] = {}
    for entity in nodes.node_id:
        kind = kind_of_entity.get(entity, "Unknown")
        counts = by_entity_class.setdefault(kind, {"entities": 0, "with_a_descriptor": 0})
        counts["entities"] += 1
        counts["with_a_descriptor"] += int(entity in entity_descriptors.index)

    result = {"graph_dirs": [str(path) for path in arguments.graph_dirs], "num_entities": int(len(nodes)),
              "num_entities_with_members": len(member_genes), "num_entities_with_a_descriptor": int(len(entity_descriptors)),
              "members_per_entity": {"median": float(np.median(member_counts)), "max": int(member_counts.max())},
              "rank": recorded["rank"], "relative_alpha": recorded["relative_alpha"], "num_targets": int(targets.shape[1]),
              "proteins_in_fit": int(fit_rows.sum()),
              "by_entity_class": dict(sorted(by_entity_class.items(), key=lambda item: -item[1]["entities"])),
              "observed_against_fitted_projection": {"median_correlation": float(np.median(correlations)),
                                                     "minimum_correlation": float(np.min(correlations)),
                                                     "maximum_correlation": float(np.max(correlations)),
                                                     "components_above_0_5": int(sum(value > 0.5 for value in correlations)),
                                                     "per_component": [round(value, 4) for value in correlations]},
              "single_member_entities": {"count": len(single_member),
                                         "median_correlation_with_the_member_descriptor": float(np.median(single_member_correlations)) if single_member_correlations else float("nan")}}
    destination = arguments.output_dir / "complex_descriptors.parquet"
    entity_descriptors.to_parquet(destination)
    (arguments.output_dir / "complex_descriptor_fit.json").write_text(json.dumps(result, indent=1) + "\n")
    arguments.report.write_text(markdown_report(result))
    print(json.dumps({key: value for key, value in result.items() if key != "observed_against_fitted_projection"}, indent=1))
    print(f"wrote {destination} ({len(entity_descriptors)} entities x {entity_descriptors.shape[1]}), "
          f"{arguments.output_dir / 'complex_descriptor_fit.json'} and {arguments.report}")


if __name__ == "__main__":
    main()

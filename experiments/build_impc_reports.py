"""Build the IMPC knockout evidence reports (mechanistic_pathway_learning/evidence/impc_knockout_phenotypes.py).

Reads the pinned IMPC release 24.0 files under data/raw/impc, HGNC for the mouse-to-human map and the graph's gene
nodes; writes data/processed/impc/impc_reports.parquet (the evidence_reports schema plus rubric_cross_species and
rubric_proxy_validity), impc_summary.json and the generated docs/impc_knockout_evidence.md.

Usage:
  python experiments/build_impc_reports.py --graph-dir data/processed/graph_full
  python experiments/build_impc_reports.py --include-weak     # also the weak proxies (tremors, gait, stereotypy)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from mechanistic_pathway_learning.documentation import provenance_stamp
from mechanistic_pathway_learning.evidence.clinical_trial_adverse_events import rows_to_dataframe
from mechanistic_pathway_learning.evidence.impc_knockout_phenotypes import (
    DEFAULT_CROSSWALK_PATH,
    IMPC_RELEASE,
    SOURCE_NAME,
    VALIDITY_READ_BY_DEFAULT,
    VALIDITY_READ_WITH_WEAK,
    build_reports,
    collect_assertions,
    collect_tests,
    mouse_to_human_symbols,
    read_crosswalk,
    read_statistical_results,
    write_summary,
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--impc-dir", type=Path, default=Path("data/raw/impc"))
    parser.add_argument("--hgnc", type=Path, default=Path("data/raw/hgnc/hgnc_complete_set.txt"))
    parser.add_argument("--graph-dir", type=Path, default=Path("data/processed/graph_full"))
    parser.add_argument("--crosswalk", type=Path, default=DEFAULT_CROSSWALK_PATH)
    parser.add_argument("--output-dir", type=Path, default=Path("data/processed/impc"))
    parser.add_argument("--markdown-output", type=Path, default=Path("docs/impc_knockout_evidence.md"))
    parser.add_argument("--include-weak", action="store_true")
    arguments = parser.parse_args()

    validities = VALIDITY_READ_WITH_WEAK if arguments.include_weak else VALIDITY_READ_BY_DEFAULT
    crosswalk = read_crosswalk(arguments.crosswalk)
    codes = {code for row in crosswalk if row.validity in validities for code in row.negative_procedure_codes}
    nodes = pd.read_parquet(arguments.graph_dir / "nodes.parquet", columns=["node_id", "node_type", "gene_symbol"])
    genes = nodes[nodes.node_type == "gene"]
    node_of_symbol = {str(symbol): str(node_id) for node_id, symbol in zip(genes.node_id, genes.gene_symbol) if isinstance(symbol, str)}
    mouse_to_human = mouse_to_human_symbols(arguments.hgnc)
    assertions = collect_assertions(arguments.impc_dir / "genotype-phenotype-assertions-ALL.csv.gz")
    tests = collect_tests(read_statistical_results(arguments.impc_dir / "statistical-results-ALL.csv.gz", codes))
    rows, counts = build_reports(assertions, tests, mouse_to_human, node_of_symbol, crosswalk, validities)
    counts["mouse_genes_with_a_human_orthologue"] = len(mouse_to_human)
    counts["graph_gene_nodes"] = len(node_of_symbol)

    arguments.output_dir.mkdir(parents=True, exist_ok=True)
    table = rows_to_dataframe(rows)
    for column in ("rubric_cross_species", "rubric_proxy_validity"):
        table[column] = pd.Series([row.get(column, 0.0) for row in rows], dtype="float64") if rows else pd.Series(dtype="float64")
    table.to_parquet(arguments.output_dir / "impc_reports.parquet", index=False)
    write_summary(arguments.output_dir / "impc_summary.json", counts, crosswalk, validities)

    positives = int((table.report_value == 1).sum()) if len(table) else 0
    negatives = int((table.report_value == 0).sum()) if len(table) else 0
    genes_with_reports = int(table.perturbation_id.nunique()) if len(table) else 0
    lines = [
        "# IMPC knockout phenotypes as evidence (generated by experiments/build_impc_reports.py — do not edit by hand)", "",
        provenance_stamp("experiments/build_impc_reports.py", [f"IMPC release {IMPC_RELEASE} (data/raw/impc)", str(arguments.hgnc), str(arguments.graph_dir), str(arguments.crosswalk)]), "",
        f"Source `{SOURCE_NAME}`, evidence class animal (grade D, a soft prior and never a label): {counts['mouse_genes_with_assertions']:,} knockout genes carry "
        f"a significant phenotype and {counts['mouse_genes_tested_on_read_procedures']:,} were tested on a procedure the crosswalk reads; "
        f"{counts['no_one_to_one_human_gene']:,} had no one-to-one human gene by HGNC and {counts['human_gene_not_in_graph']:,} a human gene not in the graph. "
        f"**{positives:,} positive reports** (a mapped MP term asserted) and **{negatives:,} negative reports** (tested, no significant call among the "
        f"symptom's terms) over {genes_with_reports:,} human genes; {counts['negatives_blocked_by_a_hit']:,} candidate negatives were set aside because the "
        f"gene did carry a hit for the symptom. Validities read: {', '.join(validities)}.", "",
        "A mouse readout stands for a human symptom only as far as the crosswalk's validity says (`configs/impc_symptom_crosswalk.csv`); every row carries "
        "`rubric_cross_species` 1 and `rubric_proxy_validity` for the reliability fit, and a negative is an absence at the power of the mutants tested, "
        "not a demonstration of no effect. Symptoms with no defensible proxy (suicidality, abnormal dreams, emotional lability, psychosis as a disorder, and "
        "others the crosswalk lists as none) have no rows.", "",
    ]
    if len(table):
        by_symptom = table.groupby(["symptom", "relation"]).report_value.agg(["count", "sum"])
        lines += ["| symptom | relation | reports | positive | negative |", "| --- | --- | --- | --- | --- |"]
        for (symptom, relation), row in by_symptom.sort_values("count", ascending=False).iterrows():
            lines.append(f"| {symptom} | {relation} | {int(row['count'])} | {int(row['sum'])} | {int(row['count'] - row['sum'])} |")
        lines.append("")
    arguments.markdown_output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(table)} reports for {genes_with_reports} genes to {arguments.output_dir}; {arguments.markdown_output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Where the graph needs a conjunction and has a disjunction (the user, 9 October 2026: "the protein / gene split
doesn't show a way of requiring multiple genes AND'd together for a protein node only OR'd").

Reactome distinguishes a Complex, whose members are all required at once, from a DefinedSet or CandidateSet, whose
members are alternatives. The graph flattens both into one relation, `member_of` with sign +1, and both encoders
aggregate a node's incoming edges additively with an in-degree divisor, so losing one of k members removes 1/k of
the entity's input whichever it is. For a set that is close to right: k interchangeable members, one gone, a
fraction of the pool gone. For an obligate complex it understates the loss, because losing one subunit abolishes the
assembly rather than shrinking it by 1/k.

This script measures the size of that gap from the graph and the Reactome source, without changing either:

  - every protein entity node by its Reactome class, and how many take two or more distinct protein members;
  - the relation and sign the graph gives them, which is what shows that the two classes are wired the same;
  - the study's gene perturbations that sit inside a conjunction, which is who the understatement applies to;
  - the member count per conjunction, since 1/k is how far the input falls short.

The gene-to-protein split is reported beside them, because that is where the question was asked: a protein node with
several genes arises only where one reviewed UniProt entry lists them, which is redundancy and not a conjunction, so
the split's additive reading is right there and the conjunctions are one level up, at the entities.

Writes docs/complex_conjunction_semantics.md. Changes no graph. Idempotent.

Usage:
  python experiments/measure_complex_conjunction_semantics.py
"""
from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

import pandas as pd

from mechanistic_pathway_learning.graph.reactome_import import parse_reactome_sbml

PROTEIN_ENTITY_TYPE = "protein_entity"
MEMBER_RELATION = "member_of"
ENCODES_RELATION = "encodes"
CONJUNCTION_KIND = "Complex"
DISJUNCTION_KINDS = ("DefinedSet", "CandidateSet", "OpenSet")
OUTPUT_DOCUMENT = Path("docs/complex_conjunction_semantics.md")


def reactome_entity_kinds(reactome_directory: Path) -> dict[str, str]:
    """Protein entity node id -> its Reactome class. The node table does not carry the class, so it is read back
    from the pinned SBML, the same way experiments/build_complex_descriptors.py reads it."""
    kinds = {}
    for path in sorted(reactome_directory.glob("*.sbml")):
        species, _ = parse_reactome_sbml(path.read_text())
        for species_id, entity in species.items():
            kinds[f"RCTE_{species_id.split('_')[-1]}"] = entity.kind
    return kinds


def entity_membership(nodes: pd.DataFrame, edges: pd.DataFrame) -> pd.DataFrame:
    """One row per protein entity that has members, with its distinct member count."""
    entity_ids = set(nodes.node_id[nodes.node_type == PROTEIN_ENTITY_TYPE])
    members = edges[(edges.relation_type == MEMBER_RELATION) & (edges.target_id.isin(entity_ids))]
    counts = members.groupby("target_id").source_id.nunique().rename("distinct_members")
    return counts.reset_index().rename(columns={"target_id": "entity_id"}), members


def study_genes_inside(members: pd.DataFrame, entity_ids: set, edges: pd.DataFrame, nodes: pd.DataFrame,
                       perturbations: set) -> tuple[int, int]:
    """Member protein nodes of these entities, and how many of the genes behind them the study perturbs."""
    encodes = edges[edges.relation_type == ENCODES_RELATION]
    gene_of_protein = dict(zip(encodes.target_id, encodes.source_id))
    symbol_of_node = dict(zip(nodes.node_id, nodes.gene_symbol))
    member_proteins = set(members.source_id[members.target_id.isin(entity_ids)])
    symbols = {symbol_of_node.get(gene_of_protein[protein]) for protein in member_proteins if protein in gene_of_protein}
    return len(member_proteins), len(symbols & perturbations)


def write_document(kinds_of_all: Counter, kinds_of_multi: Counter, member_counts: dict, reach: dict,
                   signs: dict, genes_per_protein: pd.Series, graph_sizes: dict) -> None:
    conjunctions, disjunctions = kinds_of_multi.get(CONJUNCTION_KIND, 0), sum(kinds_of_multi.get(k, 0) for k in DISJUNCTION_KINDS)
    lines = [
        "# Conjunctive and disjunctive membership in the graph",
        "",
        "Generated by `experiments/measure_complex_conjunction_semantics.py`. Do not edit by hand.",
        "",
        f"The graph gives every membership edge one relation, `{MEMBER_RELATION}`, with sign "
        f"{', '.join(str(sign) for sign in sorted(signs))}, and both encoders aggregate a node's incoming edges",
        "additively under an in-degree divisor. So a member lost takes 1/k of the entity's input with it, whether the",
        f"entity needs all its members or any one of them. **{conjunctions} entities need all of them** and",
        f"**{disjunctions} need any one**, and nothing in the graph tells them apart.",
        "",
        "## Protein entity nodes by Reactome class",
        "",
        "| class | all entity nodes | with 2 or more distinct members | reading |",
        "| --- | --- | --- | --- |",
    ]
    for kind, number in kinds_of_all.most_common():
        reading = {CONJUNCTION_KIND: "conjunction, all members required"}.get(
            kind, "disjunction, members are alternatives" if kind in DISJUNCTION_KINDS else "single entity or not a set")
        lines.append(f"| {kind} | {number} | {kinds_of_multi.get(kind, 0)} | {reading} |")
    lines += [
        "",
        "## How far the input falls short in a conjunction",
        "",
        "A perturbation at one member of a k-member complex should abolish the assembly; the graph passes on (k-1)/k",
        "of it. The distribution of k over the conjunctions says how large that is.",
        "",
        "| distinct members k | conjunctions | input kept after losing one member |",
        "| --- | --- | --- |",
    ]
    for members, number in sorted(member_counts.items()):
        lines.append(f"| {members} | {number} | {(members - 1) / members:.2f} |")
    lines += [
        "",
        "## Who it applies to",
        "",
        "| | member protein nodes | genes the study perturbs |",
        "| --- | --- | --- |",
        f"| conjunctions (Complex) | {reach['conjunction_proteins']} | {reach['conjunction_perturbations']} |",
        f"| disjunctions (sets) | {reach['disjunction_proteins']} | {reach['disjunction_perturbations']} |",
        "",
        "## The decision of 9 October 2026, and what it costs the aggregation",
        "",
        "The user: \"i thought it would be multiple mins (one for each preserved quantity)\" and \"the inability for "
        "the linear encoder to use the true physiological min there is imposed by the encoder itself so it's still "
        "measuring a property of the encoder; it just includes a limitation of its implementation in the "
        "comparison\". So the message-passing encoder takes a true minimum and the linear-response encoder keeps the "
        "additive in-degree average, and the two encoders are compared with that difference in them.",
        "",
        "The minimum is per channel, not over a scalar: each of the encoder's node-state channels is reduced to the "
        "smallest value its members carry, so a complex is as present as its scarcest subunit in every quantity "
        "separately. That is the stoichiometric reading of an obligate assembly and it needs no summary of a member "
        "into one number.",
        "",
        "The cost is small, which an earlier note of mine overstated. The aggregation is one stacked sparse product "
        "per layer, and on this graph it already touches 54,982 of 700,435 stacked rows. A minimum is not a matrix "
        "product, so the member edges of the conjunctions have to leave that product and be reduced separately with "
        f"a segmented minimum, then added back: {conjunctions} entities and "
        f"{reach['conjunction_proteins']} member protein nodes, against "
        f"{graph_sizes['member_edges']:,} member edges in all and {graph_sizes['edges']:,} edges in "
        "the graph. One scatter-reduce over about two percent of the rows the product already reads is not a "
        "measurable cost per forward pass; what it does cost is a second code path in the encoder, which is a "
        "maintenance cost rather than a compute one.",
        "",
        "## The gene-to-protein split, where the question was asked",
        "",
        f"{int((genes_per_protein >= 2).sum())} of {len(genes_per_protein)} protein nodes are encoded by two or more",
        "genes. That case arises only where one reviewed UniProt entry lists several genes (H3-3A and H3-3B, both",
        "encoding histone H3.3), which is two genes making the same protein, so losing one halving the product is the",
        "right reading and the split needs no conjunction. The conjunctions are at the entities above, not here.",
    ]
    OUTPUT_DOCUMENT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT_DOCUMENT}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--graph-dir", type=Path, default=Path("data/processed/graph_full_neuronal_split_binders"))
    parser.add_argument("--reactome-dir", type=Path, default=Path("data/raw/reactome/v97"))
    parser.add_argument("--label-selection", type=Path, default=Path("data/processed/label_selection/better_v2_full_v2.parquet"))
    arguments = parser.parse_args()

    nodes = pd.read_parquet(arguments.graph_dir / "nodes.parquet")
    edges = pd.read_parquet(arguments.graph_dir / "edges.parquet")
    kind_of_entity = reactome_entity_kinds(arguments.reactome_dir)
    counts, members = entity_membership(nodes, edges)
    perturbations = set(pd.read_parquet(arguments.label_selection).perturbation_id)

    entity_ids = set(nodes.node_id[nodes.node_type == PROTEIN_ENTITY_TYPE])
    multi = counts[counts.distinct_members >= 2]
    kinds_of_all = Counter(kind_of_entity.get(entity, "not in the pinned SBML") for entity in entity_ids)
    kinds_of_multi = Counter(kind_of_entity.get(entity, "not in the pinned SBML") for entity in multi.entity_id)
    conjunction_ids = {entity for entity in multi.entity_id if kind_of_entity.get(entity) == CONJUNCTION_KIND}
    disjunction_ids = {entity for entity in multi.entity_id if kind_of_entity.get(entity) in DISJUNCTION_KINDS}
    conjunction_proteins, conjunction_perturbations = study_genes_inside(members, conjunction_ids, edges, nodes, perturbations)
    disjunction_proteins, disjunction_perturbations = study_genes_inside(members, disjunction_ids, edges, nodes, perturbations)
    member_counts = multi[multi.entity_id.isin(conjunction_ids)].distinct_members.value_counts().to_dict()

    encodes = edges[edges.relation_type == ENCODES_RELATION]
    write_document(kinds_of_all, kinds_of_multi, member_counts,
                   {"conjunction_proteins": conjunction_proteins, "conjunction_perturbations": conjunction_perturbations,
                    "disjunction_proteins": disjunction_proteins, "disjunction_perturbations": disjunction_perturbations},
                   set(edges.loc[edges.relation_type == MEMBER_RELATION, "sign"].unique()),
                   encodes.groupby("target_id").source_id.nunique(),
                   {"member_edges": int((edges.relation_type == MEMBER_RELATION).sum()), "edges": len(edges)})
    print(f"conjunctions with 2 or more members: {len(conjunction_ids)}, disjunctions: {len(disjunction_ids)}")
    print(f"study perturbations inside a conjunction: {conjunction_perturbations}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

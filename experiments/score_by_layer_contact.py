"""Score a graph variant against its twin only on the genes the variant's added layer reaches.

A layer added to the graph can only change the prediction for a gene whose propagation passes through it, so a
comparison over every held-out gene dilutes the layer's effect by the genes it never reaches. This script splits the
perturbation genes by contact with the layer, defined from the two graphs alone and fixed before any score is read:
a gene is in contact when its node has at least one incident edge in the variant graph that the base graph does not
have. For each A:B pair (A built on the variant, B its twin on the base graph) it reports macro AUPRC on the contacted
genes, the other genes and all genes, each model's lift over popularity on the same genes, and the paired bootstrap of
A minus B over perturbations. Out-of-fold predictions are pooled across folds, since one fold holds too few contacted
genes to score. The random walk on the base graph is listed for reference.

Usage: python experiments/score_by_layer_contact.py --variant-graph data/processed/graph_neuronal --pairs A:B ...
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from experiments.compare_twin_runs import pooled_matrix, read_run
from experiments.score_by_pathway_split import macro_auprc
from mechanistic_pathway_learning.evaluation.experiment_data import load_experiment_data
from mechanistic_pathway_learning.evaluation.ranking_and_calibration_metrics import paired_bootstrap_macro_difference

MINIMUM_POSITIVES_TO_SCORE = 5


def contacted_genes(base_graph: Path, variant_graph: Path, genes: list[str]) -> np.ndarray:
    """Boolean per gene: its GENE:<symbol> node has an incident edge in the variant that the base graph lacks."""
    def edge_keys(directory: Path) -> set[tuple[str, str, str]]:
        edges = pd.read_parquet(directory / "edges.parquet")
        return set(zip(edges.source_id, edges.target_id, edges.relation_type))

    added = edge_keys(variant_graph) - edge_keys(base_graph)
    endpoints = {source for source, _, _ in added} | {target for _, target, _ in added}
    return np.array([f"GENE:{gene}" in endpoints for gene in genes])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base-graph", type=Path, default=Path("data/processed/graph"))
    parser.add_argument("--variant-graph", type=Path, required=True)
    parser.add_argument("--evidence-dir", type=Path, default=Path("data/processed/evidence"))
    parser.add_argument("--baseline-dir", type=Path, default=Path("runs/baselines_disease_cluster"))
    parser.add_argument("--pairs", nargs="+", required=True, help="A:B, A on the variant graph and B its twin")
    parser.add_argument("--num-bootstrap", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()

    data = load_experiment_data(arguments.base_graph, arguments.evidence_dir, group_by="disease_cluster")
    outcomes = (data.outcomes >= 0.5).astype(float)
    genes = list(data.perturbation_ids)
    contact = contacted_genes(arguments.base_graph, arguments.variant_graph, genes)
    if json.loads((arguments.baseline_dir / "perturbation_ids.json").read_text()) != genes:
        raise ValueError("baseline predictions are not in the evidence table's perturbation order")
    reference = {name: np.load(arguments.baseline_dir / f"predictions_grouped_{name}.npy")
                 for name in ("popularity", "random_walk_with_restart")}
    subsets = {"genes in contact with the added layer": np.where(contact)[0], "other genes": np.where(~contact)[0],
               "all genes": np.arange(len(genes))}

    lines = [
        f"# Scores by contact with the layer {arguments.variant_graph.name} adds (generated by experiments/score_by_layer_contact.py)",
        "",
        f"{len(genes)} perturbation genes; {int(contact.sum())} are in contact with the layer that {arguments.variant_graph} adds to "
        f"{arguments.base_graph} (an incident edge the base graph lacks), defined from the graphs alone before any score was read. "
        f"Out-of-fold predictions pooled across five disease-cluster folds; macro AUPRC over symptoms with at least "
        f"{MINIMUM_POSITIVES_TO_SCORE} positives among the rows; paired bootstrap over perturbations ({arguments.num_bootstrap} resamples), "
        "95 percent intervals, not corrected.",
        "",
        "| genes | count | positive pairs | symptoms scored |",
        "|---|---|---|---|",
    ]
    for name, rows in subsets.items():
        lines.append(f"| {name} | {len(rows)} | {int(outcomes[rows].sum())} | {macro_auprc(reference['popularity'][rows], outcomes[rows])[1]} |")
    lines.append("")
    for pair in arguments.pairs:
        run, twin = pair.split(":")
        matrices = {}
        for name in (run, twin):
            _, predictions = read_run(name)
            matrix, scored = pooled_matrix(predictions, data)
            if not scored.all():
                raise ValueError(f"{name} lacks out-of-fold predictions for {int((~scored).sum())} perturbations")
            matrices[name] = matrix
        lines += [f"## {run} minus {twin}", "",
                  f"| genes | {run} | {twin} | random walk | popularity | {run} minus {twin}, paired [95% CI] |",
                  "|---|---|---|---|---|---|"]
        for subset_name, rows in subsets.items():
            scores = {name: macro_auprc(matrix[rows], outcomes[rows])[0] for name, matrix in {**matrices, **reference}.items()}
            comparison = paired_bootstrap_macro_difference(matrices[run][rows], matrices[twin][rows], outcomes[rows],
                                                           num_bootstrap=arguments.num_bootstrap, random_seed=arguments.seed,
                                                           minimum_positives=MINIMUM_POSITIVES_TO_SCORE)
            lines.append(f"| {subset_name} | {scores[run]:.3f} | {scores[twin]:.3f} | {scores['random_walk_with_restart']:.3f} | "
                         f"{scores['popularity']:.3f} | {comparison['difference']:+.3f} [{comparison['lower']:+.3f}, {comparison['upper']:+.3f}] |")
        lines.append("")
    lines.append("Contacted genes: " + ", ".join(gene for gene, touched in zip(genes, contact) if touched) + ".")
    lines.append("")
    arguments.output.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()

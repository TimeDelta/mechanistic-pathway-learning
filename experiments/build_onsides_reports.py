"""Build the OnSIDES later label slice as report rows and compare it with the SIDER-based drug pairs.

Usage:
  python experiments/build_onsides_reports.py            # writes data/processed/onsides/onsides_reports.parquet, a summary and docs/onsides_label_slice.md
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import pandas as pd

from mechanistic_pathway_learning.evidence.load_drug_label_events import read_preferred_term_to_target_symptom
from mechanistic_pathway_learning.evidence.load_onsides_label_events import ONSIDES_RELEASE, ONSIDES_RELEASE_DATE, aggregate_label_statements, load_onsides_tables, onsides_reports
from mechanistic_pathway_learning.evidence.onsides_identifier_bridge import load_ingredient_identifier_bridge


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--onsides-parquet-dir", type=Path, default=Path("data/raw/onsides/v3.1.1/parquet"))
    parser.add_argument("--bridge", type=Path, default=Path("data/raw/onsides/v3.1.1/ingredient_identifier_bridge.json"))
    parser.add_argument("--chembl-dir", type=Path, default=Path("data/raw/chembl"))
    parser.add_argument("--graph-dir", type=Path, default=Path("data/processed/graph_full"))
    parser.add_argument("--crosswalk", type=Path, default=Path("docs/symptom_crosswalk.csv"))
    parser.add_argument("--evidence-dir", type=Path, default=Path("data/processed/evidence_full"), help="assembled table whose SIDER drug pairs define the overlap")
    parser.add_argument("--output-dir", type=Path, default=Path("data/processed/onsides"))
    parser.add_argument("--markdown-output", type=Path, default=Path("docs/onsides_label_slice.md"))
    arguments = parser.parse_args()

    tables = load_onsides_tables(arguments.onsides_parquet_dir)
    statements = aggregate_label_statements(tables, read_preferred_term_to_target_symptom(arguments.crosswalk))
    bridges = load_ingredient_identifier_bridge(arguments.bridge)
    mechanisms = json.loads((arguments.chembl_dir / "mechanisms.json").read_text())
    mechanisms_by_molecule: dict[str, list[dict]] = defaultdict(list)
    for mechanism in mechanisms:
        for key in {mechanism.get("molecule_chembl_id"), mechanism.get("parent_molecule_chembl_id")}:
            if key:
                mechanisms_by_molecule[key].append(mechanism)
    targets = json.loads((arguments.chembl_dir / "targets.json").read_text())
    nodes = pd.read_parquet(arguments.graph_dir / "nodes.parquet")
    genes = nodes[nodes.node_type == "gene"]
    node_by_symbol = {symbol: node_id for symbol, node_id in zip(genes.gene_symbol, genes.node_id) if isinstance(symbol, str) and symbol}
    reports, counts = onsides_reports(statements, bridges, mechanisms_by_molecule, targets, node_by_symbol)

    arguments.output_dir.mkdir(parents=True, exist_ok=True)
    reports.to_parquet(arguments.output_dir / "onsides_reports.parquet", index=False)
    qualifying = reports[reports.qualifies]
    sider_pairs = set()
    if (arguments.evidence_dir / "evidence_records.parquet").exists():
        records = pd.read_parquet(arguments.evidence_dir / "evidence_records.parquet")
        drug_rows = records[(records.perturbation_type == "drug") & (records.relation == "induces") & (records.grade.isin(["A", "B"]) if "grade" in records else True)]
        sider_pairs = set(zip(drug_rows.perturbation_id, drug_rows.symptom))
    onsides_pairs = set(zip(qualifying.perturbation_id, qualifying.symptom))
    overlap = {"pairs_in_both": len(sider_pairs & onsides_pairs), "sider_only": len(sider_pairs - onsides_pairs), "onsides_only": len(onsides_pairs - sider_pairs),
               "sider_pairs": len(sider_pairs), "onsides_pairs": len(onsides_pairs),
               "onsides_only_by_symptom": pd.Series([symptom for _, symptom in onsides_pairs - sider_pairs]).value_counts().to_dict() if onsides_pairs - sider_pairs else {}}
    summary = {"release": ONSIDES_RELEASE, "release_date": ONSIDES_RELEASE_DATE, "counts": counts, "overlap": overlap,
               "reports_by_symptom": qualifying.symptom.value_counts().to_dict(), "reports_by_country": qualifying.source_country.value_counts().to_dict(),
               "reports_by_section": qualifying.label_section.value_counts().to_dict(), "reports_by_term_type": qualifying.meddra_term_type.value_counts().to_dict(),
               "qualifying_drugs_unified_with_sider": int(qualifying[qualifying.unified_with_sider].perturbation_id.nunique()),
               "qualifying_drugs_onsides_only": int(qualifying[~qualifying.unified_with_sider].perturbation_id.nunique())}
    (arguments.output_dir / "onsides_summary.json").write_text(json.dumps(summary, indent=1))

    lines = [f"# OnSIDES {ONSIDES_RELEASE} later label slice (generated by experiments/build_onsides_reports.py)", "",
             f"Data release {ONSIDES_RELEASE_DATE} (CC BY 4.0). One report per deduplicated label statement (ingredient, target symptom, MedDRA term, label section, country). "
             f"Statements: {counts['statements']}; qualifying reports (single mechanism target, ATC N proxy or no ATC known, target gene in the graph): {counts['qualifying_reports']} "
             f"from {counts['qualifying_ingredients']} ingredients and {counts['qualifying_perturbations']} perturbations ({summary['qualifying_drugs_unified_with_sider']} shared with SIDER, {summary['qualifying_drugs_onsides_only']} OnSIDES-only). "
             f"Disqualified statements by reason: {counts['disqualified']}; statements of ingredients without a bridge entry: {counts['ingredients_without_bridge']}.", "",
             "MedDRA term names are not reproduced here; identifiers and target symptoms only.", "",
             "## Pair-level overlap with the SIDER drug pairs of the assembled table (relation induces, grades A and B)", "",
             f"Pairs in both: {overlap['pairs_in_both']}; SIDER only (on 2015 labels, absent from current labels or from the OnSIDES extraction): {overlap['sider_only']}; "
             f"OnSIDES only (the later slice; a pair absent from SIDER 4.1 may still have been on a 2015 label that SIDER missed): {overlap['onsides_only']}.", "",
             "| symptom | OnSIDES-only pairs |", "|---|---|"]
    lines += [f"| {symptom} | {count} |" for symptom, count in sorted(overlap["onsides_only_by_symptom"].items())]
    lines += ["", "## Qualifying reports", "", "| symptom | reports |", "|---|---|"] + [f"| {s} | {c} |" for s, c in sorted(summary["reports_by_symptom"].items())]
    lines += ["", "| country | reports |", "|---|---|"] + [f"| {s} | {c} |" for s, c in sorted(summary["reports_by_country"].items())]
    lines += ["", "| label section | reports |", "|---|---|"] + [f"| {s} | {c} |" for s, c in sorted(summary["reports_by_section"].items())]
    lines += ["", "## Design document changes to apply", "",
              "4.2 (E2, both slices): SIDER 4.1 supplies the 2015 label slice and OnSIDES v3.1.1 the current-label slice; both are grade B label evidence, OnSIDES without frequencies but with the label section, the extraction score, the label count and the country as rubric features; ingredients are unified with SIDER drugs through their ChEMBL parent so both sources report on one perturbation.",
              "6.1 (pharmacological time split): SIDER 2015 pairs train, OnSIDES-only pairs test, with the caveat that a pair absent from SIDER 4.1 may have existed on a 2015 label; OnSIDES rows are dated by the release (an upper bound).",
              "10 (layout): data/processed/onsides/onsides_reports.parquet; mechanistic_pathway_learning/evidence/load_onsides_label_events.py, onsides_identifier_bridge.py; experiments/fetch_onsides_identifier_bridge.py, build_onsides_reports.py.",
              "12 (status): the counts above."]
    arguments.markdown_output.write_text("\n".join(lines) + "\n")
    print(json.dumps({"counts": counts, "overlap": {k: v for k, v in overlap.items() if k != "onsides_only_by_symptom"}}, indent=0))


if __name__ == "__main__":
    main()

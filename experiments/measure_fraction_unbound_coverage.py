"""How far the pinned fraction unbound database reaches over this study's drugs, which is what decides whether
stage 2 of docs/plasma_protein_binding.md can be built (the free fraction per drug, and with it orosomucoid's role).

Reads the database pinned by experiments/fetch_fraction_unbound_database.py (Al-Qassabi et al., CC BY 4.0,
https://doi.org/10.48420/25243138.v1) and the study's drug perturbations, and reports, per drug the database holds:
the major binding protein (albumin, orosomucoid or both), the fraction unbound in the reference population and the
same drug's fraction unbound in each special population the database covers. Writes its report; changes nothing.

Drug names are matched exactly after lowercasing, with one synonym (meperidine is pethidine). Names that only look
alike are not matched and are listed instead, so that a reader can see what a wider synonym table would add.

Usage:
  python experiments/measure_fraction_unbound_coverage.py
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

DATABASE = Path("data/raw/plasma_protein_binding/fraction_unbound_database.xlsx")
MEASUREMENT_SHEET_PATTERN = r"^\d+_"
# the study's name on the left, the database's on the right. Kept to names that are the same drug, not near spellings.
DRUG_SYNONYMS = {"meperidine": "pethidine"}
CARRIER_NAMES = {"HSA": "albumin", "AAG": "orosomucoid", "BOTH": "both"}


def measurement_rows(database: Path = DATABASE) -> pd.DataFrame:
    """Every measurement row of the workbook, with the sheet it came from and the population it describes."""
    sheets = pd.read_excel(database, sheet_name=None)
    frames = []
    for sheet_name, frame in sheets.items():
        if not re.match(MEASUREMENT_SHEET_PATTERN, sheet_name):
            continue
        frame = frame.copy()
        frame["sheet"] = sheet_name
        frame["population"] = sheet_name.split("_")[1]
        frames.append(frame)
    rows = pd.concat(frames, ignore_index=True)
    rows["drug_lower"] = rows["Drug"].astype(str).str.strip().str.lower()
    rows["carrier"] = rows["Major Binding Protein"].astype(str).str.strip().str.upper().map(CARRIER_NAMES)
    return rows


def study_drugs(evidence_directory: Path, lockbox: Path) -> pd.DataFrame:
    records = pd.read_parquet(evidence_directory / "evidence_records.parquet")
    drugs = (records[records.perturbation_type == "drug"][["perturbation_id", "perturbation_label"]]
             .drop_duplicates().sort_values("perturbation_label").reset_index(drop=True))
    drugs["in_lockbox"] = drugs.perturbation_id.isin(set(json.loads(lockbox.read_text())["perturbation_ids"]))
    drugs["database_name"] = drugs.perturbation_label.str.strip().str.lower().map(lambda name: DRUG_SYNONYMS.get(name, name))
    return drugs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--database", type=Path, default=DATABASE)
    parser.add_argument("--evidence-dir", type=Path, default=Path("data/processed/evidence_full_v2"))
    parser.add_argument("--lockbox", type=Path, default=Path("configs/lockbox_v2.json"))
    parser.add_argument("--output", type=Path, default=Path("docs/fraction_unbound_coverage.md"))
    arguments = parser.parse_args()

    rows = measurement_rows(arguments.database)
    drugs = study_drugs(arguments.evidence_dir, arguments.lockbox)
    covered = rows[rows.drug_lower.isin(set(drugs.database_name))]
    covered_names = set(covered.drug_lower)
    drugs["covered"] = drugs.database_name.isin(covered_names)

    lines = ["# Fraction unbound: what the pinned database covers of this study's drugs", "",
             "Generated by `experiments/measure_fraction_unbound_coverage.py`. Do not edit by hand.", "",
             f"Database: {arguments.database} (Al-Qassabi et al., CC BY 4.0, https://doi.org/10.48420/25243138.v1), "
             f"{len(rows):,} measurement rows over {rows.drug_lower.nunique()} drugs and "
             f"{rows.population.nunique()} special populations.", "",
             "Major binding protein over all its rows: "
             + ", ".join(f"{number} {name}" for name, number in rows.carrier.value_counts().items()) + ".", "",
             f"This study has {len(drugs)} drug perturbations, {int(drugs.in_lockbox.sum())} of them in the lockbox. "
             f"The database holds {int(drugs.covered.sum())} of them "
             f"({int((drugs.covered & drugs.in_lockbox).sum())} of the lockbox drugs).", "",
             "## The study's drugs the database holds", "",
             "| drug | in lockbox | major binding protein | fu, reference population | fu in special populations |",
             "|---|---|---|---|---|"]
    for row in drugs[drugs.covered].itertuples():
        drug_rows = covered[covered.drug_lower == row.database_name]
        carriers = "/".join(sorted(set(drug_rows.carrier.dropna())))
        reference = sorted({round(float(value), 4) for value in drug_rows["fu in reference population"].dropna()})
        special = "; ".join(sorted({f"{population} {float(value):.4g}" for population, value
                                    in zip(drug_rows["Special population subgroup"], drug_rows["fu in special population"])
                                    if pd.notna(value)}))
        lines.append(f"| {row.perturbation_label} | {'yes' if row.in_lockbox else 'no'} | {carriers} | "
                     f"{', '.join(str(value) for value in reference)} | {special} |")

    orosomucoid_drugs = sorted({row.perturbation_label for row in drugs[drugs.covered].itertuples()
                                if set(covered.loc[covered.drug_lower == row.database_name, "carrier"]) & {"orosomucoid", "both"}})
    lines += ["", "## Orosomucoid's share", "",
              f"{len(orosomucoid_drugs)} of the covered drugs name orosomucoid as a major binding protein: "
              + ", ".join(orosomucoid_drugs) + ".", "",
              "## The study's drugs the database does not hold", "",
              f"{int((~drugs.covered).sum())} drugs: " + ", ".join(sorted(drugs.loc[~drugs.covered, "perturbation_label"])) + ".", "",
              "A drug missing here has no free fraction from this source, so stage 2 of docs/plasma_protein_binding.md "
              "cannot rescale its seed magnitudes without a second source or a prediction, and a predicted value is "
              "exactly what the database's own paper warns against for a population whose binder concentration has "
              "moved."]
    arguments.output.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""experiments/audit_channel_conduction.py: which ion channels catalyse a reaction that reaches the membrane potential."""
import gzip

import pandas as pd

from experiments.audit_channel_conduction import (CLASSES, ION_CHANNEL_ACTIVITY, channel_genes, classify_channels, family_of,
                                                  reaction_ion_movement, render)


def toy_graph():
    nodes = pd.DataFrame({"node_id": ["GENE:A", "PROTEIN:A", "GENE:B", "PROTEIN:B", "GENE:C", "PROTEIN:C", "GENE:D", "PROTEIN:D", "GENE:E", "PROTEIN:E",
                                      "GENE:G", "RCTE_1", "R1", "R2", "R3", "VM_c", "MAM02519e", "NEURON_MAM02519c", "MAM01413e", "NEURON_MAM01413c",
                                      "MAM01965c", "MAM01965e", "PROTEIN:X"]})
    rows = [("GENE:A", "PROTEIN:A", "encodes"), ("PROTEIN:A", "R1", "catalyzed_by"), ("MAM02519e", "R1", "substrate_of"), ("R1", "NEURON_MAM02519c", "product_of"),
            ("R1", "VM_c", "changes_membrane_potential"), ("VM_c", "R1", "voltage_gates"),
            ("GENE:B", "PROTEIN:B", "encodes"), ("PROTEIN:B", "RCTE_1", "member_of"), ("RCTE_1", "R2", "catalyzed_by"), ("MAM01413e", "R2", "substrate_of"),
            ("R2", "NEURON_MAM01413c", "product_of"),
            ("GENE:C", "PROTEIN:C", "encodes"), ("PROTEIN:C", "R3", "catalyzed_by"), ("MAM01965c", "R3", "substrate_of"), ("R3", "MAM01965e", "product_of"),
            ("GENE:D", "PROTEIN:D", "encodes"), ("PROTEIN:D", "PROTEIN:X", "binds"),
            ("GENE:E", "PROTEIN:E", "encodes"),
            ("GENE:G", "R1", "catalyzed_by")]
    edges = pd.DataFrame(rows, columns=["source_id", "target_id", "relation_type"])
    return nodes, edges


def test_each_channel_takes_the_first_class_that_holds():
    nodes, edges = toy_graph()
    table = classify_channels(nodes, edges, {"A", "B", "C", "D", "E", "G", "F"}).set_index("gene")
    assert table.loc["A", "class"] == "conducts into VM_c" and table.loc["A", "voltage_gated_reactions"] == 1
    assert table.loc["B", "class"] == "moves ions, no VM_c edge", "a member of an entity that moves calcium into the pool, with no membrane-potential edge"
    assert table.loc["C", "class"] == "catalyses another reaction", "glucose is not an inorganic ion"
    assert table.loc["D", "class"] == "signalling or binding only" and table.loc["D", "edges_out_of_the_protein"] == "binds:1"
    assert table.loc["E", "class"] == "no edge out"
    assert table.loc["G", "class"] == "conducts into VM_c", "a merged graph's gene node acts for its product"
    assert "F" not in table.index, "a channel gene the graph lacks is not counted"
    assert set(table["class"]) <= set(CLASSES)


def test_ion_movement_needs_the_same_ion_on_both_sides_or_a_neuronal_pool():
    _, edges = toy_graph()
    movement = reaction_ion_movement(edges, set())
    assert movement["R1"]["feeds_vm"] and movement["R1"]["moves_ion"] and movement["R1"]["voltage_gated"]
    assert movement["R2"]["moves_ion"] and not movement["R2"]["feeds_vm"]
    assert not movement["R3"]["moves_ion"]


def test_families_by_gene_symbol():
    assert family_of("CACNA1C") == "voltage-gated calcium alpha1 (CaV)"
    assert family_of("CACNA2D1") == "calcium channel auxiliary"
    assert family_of("KCNJ13") == "inward rectifier potassium (Kir)"
    assert family_of("KCNK5") == "two-pore potassium (K2P)"
    assert family_of("SCN3B") == "sodium channel beta subunits" and family_of("SCN1A") == "voltage-gated sodium (Nav)"
    assert family_of("GRIN3A") == "ionotropic glutamate (AMPA, kainate, NMDA, delta)"
    assert family_of("P2RX7") == "P2X purinergic" and family_of("NOTACHANNEL") == "other"


def test_channel_genes_reads_propagated_function_annotations_and_skips_not_rows(tmp_path):
    gaf = tmp_path / "goa.gaf.gz"
    lines = ["!gaf-version: 2.2",
             "\t".join(["UniProtKB", "P1", "A", "", "GO:0005248", "PMID:1", "IDA", "", "F", "", "", "protein", "taxon:9606", "20200101", "UniProt"]),
             "\t".join(["UniProtKB", "P2", "B", "NOT", "GO:0005248", "PMID:1", "IDA", "", "F", "", "", "protein", "taxon:9606", "20200101", "UniProt"]),
             "\t".join(["UniProtKB", "P3", "C", "", "GO:0005248", "PMID:1", "IDA", "", "P", "", "", "protein", "taxon:9606", "20200101", "UniProt"])]
    with gzip.open(gaf, "wt") as handle:
        handle.write("\n".join(lines) + "\n")
    uniprot = pd.DataFrame({"Entry": ["P1", "P2", "P3"], "Gene Names (primary)": ["SCN1A", "NOTCHANNEL", "PROCESSONLY"]})
    ancestors = {"GO:0005248": {"GO:0005248", ION_CHANNEL_ACTIVITY}}
    assert channel_genes(uniprot, gaf, ancestors) == {"SCN1A"}, "the NOT row and the process annotation are not channel activity"


def test_the_page_lists_every_channel_that_does_not_conduct():
    nodes, edges = toy_graph()
    table = classify_channels(nodes, edges, {"A", "B", "C", "D", "E"})
    page = render(table, "graph", "Generated by test.", 5)
    assert "| conducts into VM_c | 1 |" in page and "| no edge out | 1 |" in page
    for gene in ("B", "C", "D", "E"):
        assert f"| {gene} |" in page
    assert "| A |" not in page.split("## Channels that do not conduct into VM_c", 1)[1]

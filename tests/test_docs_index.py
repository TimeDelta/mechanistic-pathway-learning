"""The landing page of docs/ (experiments/generate_docs_index.py, written by the status generator): it links every
registered document, starts from documents that exist, and its check ignores nothing but the stamp."""
from __future__ import annotations

import re

from experiments.generate_docs_index import INDEX_PATH, START_HERE, TOPICS, index_is_current, link, render_index, topic_of
from mechanistic_pathway_learning.documentation import REPOSITORY_ROOT, load_registry


def test_the_landing_page_links_every_registered_document_but_itself():
    text = render_index("Generated by `experiments/generate_docs_index.py` on 2026-10-17 at commit abc; do not edit by hand.")
    linked = set(re.findall(r"\]\(([^)]+)\)", text))
    own = str(INDEX_PATH.relative_to(REPOSITORY_ROOT))
    for path in load_registry():
        if path == own:
            assert link(path) not in linked, "the page does not list itself"
            continue
        assert link(path) in linked, f"{path} is registered but not on the landing page"


def test_the_start_list_names_registered_documents_and_every_registered_document_has_a_topic():
    registry = load_registry()
    assert all(path in registry for path, _, _ in START_HERE)
    untopiced = [path for path in registry if path != str(INDEX_PATH.relative_to(REPOSITORY_ROOT)) and topic_of(path) == "Other documents"]
    assert not untopiced, f"add a rule to TOPICS for {untopiced}"
    assert len({topic for topic, _ in TOPICS}) == len(TOPICS)


def test_links_are_relative_to_the_docs_directory():
    assert link("docs/status.md") == "status.md" and link("docs/exposure_sources/schulz2020.md") == "exposure_sources/schulz2020.md"
    assert link("README.md") == "../README.md"


def test_the_check_ignores_the_stamp_and_nothing_else():
    first = "# Documentation\n\nGenerated by `experiments/generate_docs_index.py` on 2026-10-16 at commit aaa; do not edit by hand.\n\n- [A](a.md)\n"
    second = first.replace("2026-10-16 at commit aaa", "2026-10-17 at commit bbb")
    assert index_is_current(first, second)
    assert not index_is_current(first, second.replace("[A](a.md)", "[B](b.md)"))


def test_the_committed_page_is_current():
    import subprocess

    result = subprocess.run(["python3", "experiments/generate_docs_index.py", "--check"], cwd=REPOSITORY_ROOT, capture_output=True, text=True,
                            env={"PYTHONPATH": str(REPOSITORY_ROOT), "PATH": "/usr/bin:/bin:/usr/local/bin"})
    assert result.returncode == 0, result.stdout + result.stderr

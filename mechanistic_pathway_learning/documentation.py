"""The documentation process, as code: the register of documents, the checks that keep stale statements from passing
for current ones, and the provenance stamp every generated document carries (docs/documentation_process.md).

The defect this exists to stop is the one the owner named on 15 October 2026: sessions "keep getting tripped up by
stale things". The mechanism of 15 October (a frozen registration baseline, a generated amendment history from commit
trailers, and registered rules asserted against the code) covers the registration. This module extends the same
three ideas to every document the repository holds:

  1. A register. `configs/documentation_registry.json` names every tracked Markdown document and its class. A document
     that is not registered fails the suite, so a new file has to say what kind of thing it is before it is committed.
  2. Derived state, never hand-kept. `docs/status.md` (experiments/generate_status.py) and
     `docs/decision_history.md` (experiments/generate_decision_history.py) are generated from the manifest, the
     register and the git log, and a test fails when the committed copy no longer matches what the generator says.
  3. Checks that catch the ways a statement goes stale: a path that no longer exists, a decision or item number that
     is not in the log, a generated table with no date and no commit behind it, a frozen file that changed, a living
     document that describes a container or a session as though it were the repository, a decision id that was
     renumbered or dropped.

Classes, which decide what is checked (the register's `class` field):

  generated   written by a script from data, a run or the git log. Must say which script in its first lines. Once
              regenerated after the policy date it must carry the provenance stamp `provenance_stamp` produces
              (script, date, commit, inputs). Never edited by hand.
  living      hand-written and kept current by overwriting, as the owner ruled for the registration on 15 October:
              "a copy ... that stays unmodified ... as starting file for the current state", with the living document
              "free to be overwritten". Carries `reviewed` (a date) and `as_of_commit` in the register, and never
              describes a container or a session.
  record      dated, written once and corrected by a later dated addition rather than an edit: a review, a reading of a
              source, a rebuild report, the decision log. `append_only: true` in the register means the committed text
              must be a prefix of the working-tree text.
  frozen      byte-exact, SHA-256 pinned in the register: the registration baseline.
  draft       text for the owner to act on; no claim about the current state, no checks beyond registration.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
from dataclasses import dataclass
from datetime import date
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = REPOSITORY_ROOT / "configs" / "documentation_registry.json"
DECISION_LOG_PATH = REPOSITORY_ROOT / "docs" / "open_decisions.md"
PREREGISTRATION_PATH = REPOSITORY_ROOT / "docs" / "preregistration.md"
DOCUMENT_CLASSES = ("generated", "living", "record", "frozen", "draft")
# Generated documents last changed after this date must carry the provenance stamp; the ones generated before it are
# listed by the audit as unstamped until their generator runs again, because a stamp that was not produced by the
# generator would assert a date and a commit the file cannot support.
STAMP_POLICY_DATE = date(2026, 10, 16)
# Paths under these roots exist only on a container's disk (gitignored), so a reference to one is not a dangling
# reference to the repository.
RUNTIME_ROOTS = ("data/raw/", "data/processed/", "data/cache/", "runs/", "checkpoints/")
TRACKED_ROOTS = ("docs/", "configs/", "experiments/", "mechanistic_pathway_learning/", "scripts/", "slurm/", "tests/", "data/releases/", ".claude/")
# A living document describes the repository, not the machine a session happened to run on. These phrases are the
# ones that have carried container or session state into the documents so far (docs/job_harness.md, decision 9.47).
SESSION_STATE_PHRASES = ("this container", "this session", "the earlier session's disk", "the old container", "the new container's disk")
STAMP_PATTERN = re.compile(r"Generated by `?(?P<generator>[A-Za-z0-9_./-]+\.py)`? on (?P<date>\d{4}-\d{2}-\d{2}) at commit (?P<commit>[0-9a-f]{7,40}(?:-dirty)?)")
# The form experiments/write_descriptor_column_doc.py used before the stamp existed; it carries the same three facts.
EARLIER_STAMP_PATTERN = re.compile(r"generated (?P<date>\d{4}-\d{2}-\d{2}) by (?P<generator>[A-Za-z0-9_./-]+\.py) from the code at commit (?P<commit>[0-9a-f]{7,40})")


# ----------------------------------------------------------------------------------------------------------------------
# git and files


def git_output(*arguments: str, cwd: Path = REPOSITORY_ROOT) -> str:
    return subprocess.run(["git", *arguments], cwd=cwd, capture_output=True, text=True, check=True).stdout


def tracked_markdown_documents(root: Path = REPOSITORY_ROOT) -> list[str]:
    """Every Markdown file git tracks under docs/ plus the two root documents sessions read first."""
    listed = git_output("ls-files", "README.md", "CLAUDE.md", "docs", cwd=root).split()
    return sorted(path for path in listed if path.endswith(".md"))


def head_commit(root: Path = REPOSITORY_ROOT, short: bool = True) -> str:
    return git_output("rev-parse", "--short" if short else "--verify", "HEAD", cwd=root).strip()


def last_change_date(path: str, root: Path = REPOSITORY_ROOT) -> date | None:
    """The date of the last commit that touched the file; today when the working tree differs from HEAD."""
    status = git_output("status", "--porcelain", "--", path, cwd=root).strip()
    if status:
        return date.today()
    logged = git_output("log", "-1", "--format=%ad", "--date=short", "--", path, cwd=root).strip()
    return date.fromisoformat(logged) if logged else None


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# ----------------------------------------------------------------------------------------------------------------------
# the register


@dataclass(frozen=True)
class RegisteredDocument:
    path: str
    document_class: str
    fields: dict

    @property
    def generator(self) -> str | None:
        return self.fields.get("generator")


def load_registry(registry_path: Path = REGISTRY_PATH) -> dict[str, RegisteredDocument]:
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    documents = {}
    for path, entry in registry["documents"].items():
        document_class = entry.get("class")
        if document_class not in DOCUMENT_CLASSES:
            raise ValueError(f"{path}: class {document_class!r} is not one of {DOCUMENT_CLASSES}")
        documents[path] = RegisteredDocument(path, document_class, entry)
    return documents


def unregistered_and_missing(registry: dict[str, RegisteredDocument], root: Path = REPOSITORY_ROOT) -> tuple[list[str], list[str]]:
    """(tracked documents the register does not name, registered paths that are not tracked)."""
    tracked = set(tracked_markdown_documents(root))
    return sorted(tracked - set(registry)), sorted(set(registry) - tracked)


# ----------------------------------------------------------------------------------------------------------------------
# the provenance stamp for generated documents


def provenance_stamp(generator: str, inputs: list[str] | None = None, root: Path = REPOSITORY_ROOT, today: date | None = None) -> str:
    """The line every generated document carries first: which script, when, at which commit, from which inputs.

    `inputs` names what the script read, as paths or short labels ("the git log"), so a reader can tell whether the
    table reflects the data in front of them. The commit is HEAD, which is the code that ran; a dirty tree is marked
    so the stamp never claims a clean commit it did not have.
    """
    commit = head_commit(root)
    if git_output("status", "--porcelain", "--untracked-files=no", cwd=root).strip():
        commit = f"{commit}-dirty"
    read = f" from {', '.join(inputs)}" if inputs else ""
    return f"Generated by `{generator}` on {(today or date.today()).isoformat()} at commit {commit}{read}; do not edit by hand."


def parse_stamp(text: str) -> dict | None:
    """The stamp's fields when one of the first five lines carries it, else None."""
    for line in text.splitlines()[:5]:
        for pattern in (STAMP_PATTERN, EARLIER_STAMP_PATTERN):
            match = pattern.search(line)
            if match:
                return match.groupdict()
    return None


def names_its_generator(text: str, generator: str | None) -> bool:
    """A generated document says in its first lines which script wrote it (the convention every generator here uses)."""
    head = "\n".join(text.splitlines()[:6])
    if generator and generator in head:
        return True
    # "generated by", "written by", "measured by", "built by", "read from openFDA by": the generators here all say
    # which script wrote the file, in one of those forms, within the first lines
    return bool(re.search(r"\bby `?(?:experiments|mechanistic_pathway_learning|scripts)/[A-Za-z0-9_./-]+\.py", head, flags=re.IGNORECASE))


# ----------------------------------------------------------------------------------------------------------------------
# references: paths, decisions, items


PATH_REFERENCE = re.compile(r"`(?P<path>(?:" + "|".join(re.escape(root) for root in TRACKED_ROOTS + RUNTIME_ROOTS) + r")[A-Za-z0-9_./<>*{}-]*)`")
BARE_PATH_REFERENCE = re.compile(r"(?<![\w/`])(?P<path>(?:" + "|".join(re.escape(root) for root in TRACKED_ROOTS) + r")[A-Za-z0-9_./-]*\.(?:py|md|json|yaml|csv|sh|bib|sbatch|png|txt))(?![\w/`])")
MARKDOWN_LINK = re.compile(r"\]\((?P<target>[^)\s#]+)(?:#[^)]*)?\)")


def referenced_repository_paths(text: str) -> set[str]:
    """Repository paths the text names, in backticks or bare, with runtime roots and placeholders left out."""
    found = set()
    for pattern in (PATH_REFERENCE, BARE_PATH_REFERENCE):
        for match in pattern.finditer(text):
            path = match.group("path").rstrip(".,:;")
            if path.startswith(RUNTIME_ROOTS) or any(character in path for character in "<>*{}"):
                continue
            if path.endswith("/"):
                path = path[:-1]
            found.add(path)
    return found


def dangling_paths(text: str, root: Path = REPOSITORY_ROOT) -> list[str]:
    return sorted(path for path in referenced_repository_paths(text) if not (root / path).exists())


def dangling_links(text: str, document: str, root: Path = REPOSITORY_ROOT) -> list[str]:
    """Relative Markdown links whose target is not in the tree (web links and anchors are left alone)."""
    missing = []
    for match in MARKDOWN_LINK.finditer(text):
        target = match.group("target")
        if re.match(r"[a-z]+:", target) or target.startswith("#"):
            continue
        resolved = (root / document).parent / target
        if not resolved.exists():
            missing.append(target)
    return sorted(set(missing))


# "decision 9.5", "decisions 4.2b and 4.4", "decision 9.10(a)" (the form the code uses for a lettered sub-decision)
DECISION_ID = re.compile(r"\b(?:decision|decisions)\s+(?P<id>\d+\.\d+)(?:(?P<letter>[a-z])\b|\((?P<bracketed>[a-z])\))?", flags=re.IGNORECASE)
ITEM_ID = re.compile(r"\bitem\s+(?P<id>\d+[a-z]?)\b", flags=re.IGNORECASE)


def decision_ids_in_log(text: str) -> list[str]:
    """Every decision id the log's tables carry, in file order, struck-through or not, duplicates kept."""
    ids = []
    for line in text.replace("\\n", "\n").splitlines():
        match = re.match(r"^\|\s*(~~)?(?P<id>\d+\.\d+[a-z]?)(~~)?\s*\|", line)
        if match:
            ids.append(match.group("id"))
    return ids


def closed_decision_ids(text: str) -> set[str]:
    return {match.group("id") for match in re.finditer(r"^\|\s*~~(?P<id>\d+\.\d+[a-z]?)~~\s*\|", text.replace("\\n", "\n"), flags=re.MULTILINE)}


def item_ids_in_registration(text: str) -> set[str]:
    """Items are headed `**14. ...**`, and a sub-item added later may sit in a bullet, `- **23a. ...**`."""
    return {match.group("id") for match in re.finditer(r"^(?:- )?\*\*(?P<id>\d+[a-z]?)\.\s", text, flags=re.MULTILINE)}


def decision_references(text: str) -> set[str]:
    found = set()
    for match in DECISION_ID.finditer(text):
        found.add(match.group("id") + (match.group("letter") or match.group("bracketed") or ""))
    return found


def unresolved_decision_references(text: str, known_ids: set[str]) -> list[str]:
    """A reference resolves when the log carries the id, or the decision it is a lettered sub-point of (decision
    1.3(c) is stated inside 1.3's row)."""
    return sorted(identifier for identifier in decision_references(text)
                  if identifier not in known_ids and identifier.rstrip("abcdefghijklmnopqrstuvwxyz") not in known_ids)


def unresolved_item_references(text: str, known_items: set[str]) -> list[str]:
    """An item reference resolves when the registration heads that item, or heads the item it is a sub-point of
    (item 25c is the third stratum stated inside item 25's text)."""
    unresolved = set()
    for match in ITEM_ID.finditer(text):
        identifier = match.group("id")
        if identifier not in known_items and identifier.rstrip("abcdefghijklmnopqrstuvwxyz") not in known_items:
            unresolved.add(identifier)
    return sorted(unresolved)


def literal_newline_escapes(text: str) -> list[int]:
    """Line numbers holding a literal backslash-n, which Markdown renders as text and which hides table rows from
    any reader that splits on real newlines (docs/open_decisions.md line 204 on 15 October 2026)."""
    return [number for number, line in enumerate(text.splitlines(), start=1) if "\\n" in line and not line.lstrip().startswith(("`", "    "))]


DATED_LINE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b|\b\d{1,2} (?:January|February|March|April|May|June|July|August|September|October|November|December)\b")


def session_state_phrases(text: str) -> list[str]:
    """Container or session phrases on lines that carry no date. A dated line ("on 14 October", a row of a dated
    table) scopes its claim to that day, which is what makes it a record rather than a statement about now."""
    found = []
    for line in text.splitlines():
        lowered = line.lower()
        if DATED_LINE.search(line):
            continue
        found.extend(phrase for phrase in SESSION_STATE_PHRASES if phrase in lowered and phrase not in found)
    return found


# ----------------------------------------------------------------------------------------------------------------------
# records that only grow


def committed_text(path: str, root: Path = REPOSITORY_ROOT, revision: str = "HEAD") -> str | None:
    try:
        return git_output("show", f"{revision}:{path}", cwd=root)
    except subprocess.CalledProcessError:
        return None


def append_only_violation(path: str, root: Path = REPOSITORY_ROOT) -> str | None:
    """None when the committed text is a prefix of the working-tree text; otherwise what was changed."""
    before = committed_text(path, root)
    if before is None:
        return None
    before_lines = before.rstrip("\n").splitlines()
    after_lines = (root / path).read_text(encoding="utf-8").splitlines()
    for number, (old_line, new_line) in enumerate(zip(before_lines, after_lines), start=1):
        if old_line != new_line:
            return f"committed text changes at line {number}; a record is corrected by a dated addition, not an edit"
    if len(after_lines) < len(before_lines):
        return f"committed text is cut at line {len(after_lines) + 1}; a record is corrected by a dated addition, not an edit"
    return None


def decision_ids_dropped_or_renumbered(path: str = "docs/open_decisions.md", root: Path = REPOSITORY_ROOT) -> list[str]:
    """Ids the committed log carried that the working tree no longer does. Closing a decision keeps its id."""
    before = committed_text(path, root)
    if before is None:
        return []
    after = (root / path).read_text(encoding="utf-8")
    return sorted(set(decision_ids_in_log(before)) - set(decision_ids_in_log(after)))


def duplicated_decision_ids(text: str) -> list[str]:
    ids = decision_ids_in_log(text)
    return sorted({identifier for identifier in ids if ids.count(identifier) > 1})
